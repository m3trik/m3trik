def diagram_for(name: str, workspace: Path) -> Tuple[Diagram, Optional[str]]:
    """The diagram and highlighted node a marker *name* asks for."""
    base, _, focus = name.partition("/")
    if base == "ecosystem":
        diagram = ecosystem(workspace)
    elif base in FLOWS and not focus:
        diagram = FLOWS[base]()
    else:
        known = ", ".join(["ecosystem", "ecosystem/<package>"] + sorted(FLOWS))
        raise DiagramError(f"unknown diagram {name!r} (known: {known})")
    if focus and focus not in {n.id for n in diagram.nodes}:
        raise DiagramError(f"diagram {name!r}: {base} has no node {focus!r}")
    return diagram, focus or None


def svg_name(name: str, theme: str, tag: str = "") -> str:
    base = name.replace("/", "-")
    return f"{base}-tile-{tag}-{theme}.svg" if tag else f"{base}-{theme}.svg"


def _picture(name: str, tag: str, alt: str, width: str) -> str:
    light, dark = (RAW_BASE + svg_name(name, theme, tag) for theme in ("light", "dark"))
    align = ' align="top"' if tag else ""
    return (
        f'<picture><source media="(prefers-color-scheme: dark)" srcset="{dark}">'
        f'<source media="(prefers-color-scheme: light)" srcset="{light}">'
        f'<img alt="{_esc(alt)}" src="{light}" width="{width}"{align}></picture>'
    )


#: A tiled row's slices share this much of the line, never all of it: shares
#: rounded up past the whole would wrap the last slice onto a line of its own.
ROW_SHARE = 99.9


def block(name: str, alt: str, width: int = 0, rows: Optional[List[List[Tuple[Tile, Node, str]]]] = None) -> str:
    """The generated README text for marker *name*, markers included. One image
    *width* wide, linked to the whole ecosystem for a package's own view; or, for
    a tiled diagram, its *rows* of slices, each card's linked to its repo."""
    if rows is None:
        picture = _picture(name, "", alt, str(width) if width else "100%")
        if name.startswith("ecosystem/"):
            picture = f'<a href="{OVERVIEW}">{picture}</a>'
        body = f'<p align="center">\n{picture}\n</p>'
    else:
        lines = []
        for row in rows:
            total = sum(t.box[2] - t.box[0] for t, _, _ in row)
            shares = [int(round((t.box[2] - t.box[0]) / total * ROW_SHARE * 1000)) for t, _, _ in row]
            shares[-1] += int(round(ROW_SHARE * 1000)) - sum(shares)
            cells = []
            for (tile, node, tile_alt), share in zip(row, shares):
                cell = _picture(name, tile.tag, tile_alt, f"{_n(share / 1000, 3)}%")
                if node is not None and node.link:
                    cell = f'<a href="{node.link}" title="{_esc(node.tip)}">{cell}</a>'
                cells.append(cell)
            lines.append("".join(cells))
        body = '<p align="center">\n' + "<br>\n".join(lines) + "\n</p>"
    return f"<!-- diagram:{name} -->\n{GENERATED}\n{body}\n<!-- /diagram:{name} -->"


def markers(text: str, where: str) -> List[Tuple[int, int, str]]:
    """(start, end, name) of each marker pair in *text*, outside code."""
    code = [m.span() for m in FENCE.finditer(text)]
    blanked = text
    for start, end in code:
        blanked = blanked[:start] + " " * (end - start) + blanked[end:]
    code += [m.span() for m in CODE_SPAN.finditer(blanked)]
    found = [m for m in LOOKS_LIKE_MARKER.finditer(text) if not any(a <= m.start() < b for a, b in code)]
    pairs, i = [], 0
    usage = "write <!-- diagram:<name> --> ... <!-- /diagram:<name> -->, the name in lowercase-and-hyphens"
    while i < len(found):
        m = found[i]
        closing, name = m.group(1) == "/", m.group(2)
        if not NAME.fullmatch(name) or m.group(0) != f"<!-- {m.group(1)}diagram:{name} -->":
            raise DiagramError(f"{where}: malformed marker {m.group(0)!r}: {usage}")
        if closing:
            raise DiagramError(f"{where}: marker {m.group(0)} closes nothing: {usage}")
        close = f"<!-- /diagram:{name} -->"
        if i + 1 >= len(found) or found[i + 1].group(0) != close:
            raise DiagramError(f"{where}: <!-- diagram:{name} --> has no {close} after it")
        pairs.append((m.start(), found[i + 1].end(), name))
        i += 2
    return pairs


def readmes(workspace: Path) -> List[Path]:
    """Every unit's README the manifest reaches, in manifest order."""
    data = _script("sync_workspace").load(workspace / "m3trik" / "workspace.json")
    found = []
    for unit in data["units"]:
        for rel in README_NAMES:
            path = workspace / unit["path"] / rel
            if path.is_file() and path not in found:
                found.append(path)
    return found


def _read(path: Path) -> Optional[str]:
    try:
        return path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    except FileNotFoundError:
        return None


def _drawn(name: str, workspace: Path, out_dir: Path) -> Tuple[str, Dict[Path, str]]:
    """The README block for marker *name*, and the SVG files it embeds."""
    diagram, focus = diagram_for(name, workspace)
    files: Dict[Path, str] = {}
    if name in TILED:
        nodes = {n.id: n for n in diagram.nodes}
        rows: Optional[List[List[Tuple[Tile, Node, str]]]] = None
        for theme in THEMES:
            drawn = render_tiles(diagram, theme)
            for tile, svg in drawn:
                files[out_dir / svg_name(name, theme, tile.tag)] = svg
            if rows is None:
                lay = layout(diagram, title=False)
                rows = [[(t, nodes.get(t.node), _tile_alt(diagram, t)) for t in line] for line in tiles(diagram, lay)]
        return block(name, describe(diagram), rows=rows), files
    for theme in THEMES:
        files[out_dir / svg_name(name, theme)] = render(diagram, theme, focus)
    return block(name, describe(diagram, focus), width=layout(diagram).width), files


def plan(workspace: Path = WORKSPACE) -> Tuple[Dict[Path, str], List[Path]]:
    """(each generated file's wanted text, the SVGs no README asks for)."""
    wanted: Dict[Path, str] = {}
    blocks: Dict[str, str] = {}
    out_dir = workspace / OUT_SUBDIR
    for readme in readmes(workspace):
        text = _read(readme) or ""
        new, cursor = [], 0
        for start, end, name in markers(text, readme.relative_to(workspace).as_posix()):
            if name not in blocks:
                blocks[name], files = _drawn(name, workspace, out_dir)
                wanted.update(files)
            new += [text[cursor:start], blocks[name]]
            cursor = end
        new.append(text[cursor:])
        if "".join(new) != text:
            wanted[readme] = "".join(new)
    unused = sorted(p for p in out_dir.glob("*.svg") if p not in wanted) if out_dir.is_dir() else []
    return wanted, unused


def drift(wanted: Dict[Path, str]) -> List[Path]:
    return [path for path, text in wanted.items() if _read(path) != text]


def write(path: Path, text: str) -> None:
    """*text* to *path*, keeping an existing file's line endings."""
    try:
        crlf = b"\r\n" in path.read_bytes()
    except FileNotFoundError:
        crlf = False
        path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="report drift; write nothing")
    mode.add_argument("--prune", action="store_true", help="write, and delete the SVGs no README asks for")
    args = parser.parse_args(argv)
    try:
        wanted, unused = plan(WORKSPACE)
    except (DiagramError, ValueError, OSError) as exc:  # OSError: a sibling's pyproject is missing
        print(f"generate_readme_diagrams: {exc}", file=sys.stderr)
        return 2

    def rel(p: Path) -> str:
        return p.relative_to(WORKSPACE).as_posix()

    changed = drift(wanted)
    if args.check:
        for path in changed:
            print(f"DRIFT   {rel(path)}")
    else:
        for path in changed:
            write(path, wanted[path])
            print(f"wrote   {rel(path)}")
    for path in unused:
        if args.prune:
            path.unlink()
            print(f"removed {rel(path)}")
        else:
            print(f"unused  {rel(path)} (kept: a released page may embed it; --prune deletes)")
    if args.check and changed:
        print("Run: python m3trik/scripts/generate_readme_diagrams.py")
        return 1
    if args.check or not changed:
        print(f"README diagrams in sync ({sum(p.suffix == '.svg' for p in wanted)} SVGs).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
