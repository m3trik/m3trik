def _chip(x: float, y: float, text: str, here: bool = False) -> str:
    width = _chip_width(text)
    cls = "chip here" if here else "chip"
    return (
        f'<g class="{cls}"><rect x="{_n(x)}" y="{_n(y - 9)}" width="{_n(width)}" height="18" rx="9"/>'
        f'<text x="{_n(x + width / 2)}" y="{_n(y + 3.5)}" text-anchor="middle">{_esc(text)}</text></g>'
    )


def _pill(center: Point, text: str, cls: str = "pill", attrs: str = "", inner: str = "") -> str:
    x0, y0, x1, _ = _pill_rect(center, _pill_width(text))
    return (
        f'<g class="{cls}"{attrs}><rect x="{_n(x0)}" y="{_n(y0)}" width="{_n(x1 - x0)}" '
        f'height="18" rx="9"/><text x="{_n(center[0])}" y="{_n(center[1] + 3.8)}" text-anchor="middle">'
        f"{_esc(text)}</text>{inner}</g>"
    )


def _wire_class(kind: str) -> str:
    return "w" if kind in ("requires", "flow") else f"w {kind}"


def _group(bright: bool) -> str:
    return "<g>" if bright else '<g class="dim">'


def _head(tip: Point, up: bool) -> str:
    x, y = tip
    s = 1 if up else -1
    return f"M{_n(x - 4)} {_n(y + 6 * s)}L{_n(x)} {_n(y)}L{_n(x + 4)} {_n(y + 6 * s)}"


def _draw_wires(diagram: Diagram, lay: Layout, on: Lit) -> List[Item]:
    """Links, then links within rows, then labels, so every pill sits on top."""
    out = []
    for edge in diagram.edges:
        bright = edge in on.edges
        if edge in lay.side:
            (x0, y), (x1, _) = lay.side[edge]
            out.append(Item((x0, y - 9, x1, y + 9), f'{_group(bright)}<path class="{_wire_class(edge.kind)}" '
                                                  f'd="{lay.path(edge)}"/>{_pill(((x0 + x1) / 2, y), edge.label)}</g>'))
            continue
        pts = lay.wire[edge]
        up = pts[-1][1] < pts[0][1]
        out.append(Item(_bbox(pts, 2), f'{_group(bright)}<path class="{_wire_class(edge.kind)}" d="{lay.path(edge)}"/>'
                                       f'<path class="w" d="{_head(pts[-1], up)}"/></g>'))
    for pair in diagram.pairs:
        (x0, y), (x1, _) = lay.side[pair]
        out.append(Item((x0, y - 9, x1, y + 9), f'{_group(pair in on.pairs)}<path class="w pair" '
                                              f'd="M{_n(x0)} {_n(y)}H{_n(x1)}"/>{_pill(((x0 + x1) / 2, y), pair.label)}</g>'))
    for edge, spot in lay.label.items():
        out.append(Item(_pill_rect(spot, _pill_width(edge.label)),
                        f"{_group(edge in on.edges)}{_pill(spot, edge.label)}</g>"))
    return out


def _draw_cards(diagram: Diagram, lay: Layout, on: Lit, focus: Optional[str], tiled: bool) -> List[Item]:
    out = []
    w, h = lay.card_w, lay.card_h
    for node in diagram.nodes:
        x, y = lay.box[node.id]
        classes = ["node"] + (["product"] if node.product else []) + (["focus"] if node.id == focus else [])
        if node.id not in on.nodes:
            classes.append("dim")
        parts = [f'<g class="{" ".join(classes)}">',
                 f'<rect class="nb" x="{_n(x + .5)}" y="{_n(y + .5)}" width="{_n(w - 1)}" height="{_n(h - 1)}" rx="10"/>',
                 f'<g class="ic" transform="translate({_n(x + 16)} {_n(y + 20)})">{ICONS[node.icon]}</g>',
                 f'<text class="name" x="{_n(x + TEXT_X)}" y="{_n(y + 28)}">{_esc(node.name)}</text>',
                 f'<text class="cap" x="{_n(x + TEXT_X)}" y="{_n(y + 47)}">{_esc(node.caption)}</text>']
        if node.blurb:
            lines = _wrap(node.blurb, w - 32, BLURB_SIZE)
            spans = "".join(f'<tspan x="{_n(x + 16)}" y="{_n(y + BLURB_TOP + i * BLURB_LINE)}">{_esc(t)}</tspan>'
                            for i, t in enumerate(lines))
            parts.append(f'<text class="blurb">{spans}</text>')
        right = x + w - 12
        if tiled and node.link:
            parts.append(f'<g class="go" transform="translate({_n(right - 16)} {_n(y + 12)})">{LINK_MARK}</g>')
            right -= 24
        if node.product:
            parts.append(_chip(right - _chip_width("PRODUCT"), y + 22, "PRODUCT"))
        if node.id == focus:
            parts.append(_chip(x + 12, y, "YOU ARE HERE", here=True))
        parts.append("</g>")
        out.append(Item((x, y - (9 if node.id == focus else 0), x + w, y + h), "".join(parts)))
    return out


def _visible(a: float, b: float, cycle: float, fade: float) -> str:
    """An opacity animation: shown from *a* to *b* seconds of each *cycle*."""
    fade = min(fade, (b - a) / 2)
    kept: List[Tuple[float, int]] = []
    for key in ((0.0, 0), (a, 0), (a + fade, 1), (b - fade, 1), (b, 0), (cycle, 0)):
        if not kept or kept[-1] != key:
            kept.append(key)
    return (f'<animate attributeName="opacity" dur="{_n(cycle)}s" repeatCount="indefinite" '
            f'values="{";".join(str(v) for _, v in kept)}" '
            f'keyTimes="{";".join(_n(t / cycle, 4) for t, _ in kept)}"/>')


def _pulse(lay: Layout, node: str, when: float, cycle: float, extra: str = "") -> Item:
    x, y = lay.box[node]
    peak, fade = 0.15 / cycle, 0.9 / cycle  # rise 0.15 s, gone by 0.9 s
    begin = when % cycle
    return Item(lay.rect(node), (
        f'<rect class="pulse{extra}" x="{_n(x + .5)}" y="{_n(y + .5)}" width="{_n(lay.card_w - 1)}" '
        f'height="{_n(lay.card_h - 1)}" rx="10" opacity="0">'
        f'<animate attributeName="opacity" values="0;.9;0;0" dur="{_n(cycle)}s" begin="{_n(begin)}s" '
        f'repeatCount="indefinite" keyTimes="0;{_n(peak, 4)};{_n(fade, 4)};1"/></rect>'))


def _draw_wave(diagram: Diagram, lay: Layout, on: Lit) -> List[Item]:
    """A packet crosses each band of each lit link, band by band from where the
    diagram starts (the bottom of a stack, the top of a flow), and the card it
    reaches pulses. Reduced motion hides both (the style's media query)."""
    bands = len(lay.rows) - 1
    inline = [e for e in diagram.edges if e in lay.side and e in on.edges]
    if not diagram.edges or (bands < 1 and not inline):
        return []

    def order(seg: Tuple[Point, Point]) -> int:
        top = min(i for i, y in enumerate(lay.row_y) if y + lay.card_h >= min(seg[0][1], seg[1][1]) - 0.5)
        return bands - 1 - top if diagram.upward else top

    cycle = STEP * (bands + (1 if inline else 0)) + REST
    out, arrivals = [], {}
    for edge in diagram.edges:
        if edge not in on.edges:
            continue
        ring = " ring" if edge.kind == "opens" else ""
        if edge in lay.side:
            (x0, y), (x1, _) = lay.side[edge]
            a, b = ((x0, y), (x1, y)) if lay.box[edge.src][0] < lay.box[edge.dst][0] else ((x1, y), (x0, y))
            pieces = [(f"M{_n(a[0])} {_n(a[1])}H{_n(b[0])}", (a, b), STEP * bands, edge.dst)]
        else:
            segs = lay.segments(edge)
            pieces = [(_segment_path(*s), s, STEP * order(s), edge.dst if i == len(segs) - 1 else None)
                      for i, s in enumerate(segs)]
        for d, (a, b), begin, reaches in pieces:
            arrive = TRAVEL / cycle
            out.append(Item(_bbox([a, b]), (
                f'<circle class="pkt{ring}" r="3.2" opacity="0">'
                f'<animateMotion path="{d}" dur="{_n(cycle)}s" begin="{_n(begin)}s" '
                f'repeatCount="indefinite" calcMode="linear" keyPoints="0;1;1" keyTimes="0;{_n(arrive, 4)};1"/>'
                f'<animate attributeName="opacity" values="0;1;1;0;0" dur="{_n(cycle)}s" begin="{_n(begin)}s" '
                f'repeatCount="indefinite" keyTimes="0;{_n(0.15 * arrive, 4)};{_n(0.85 * arrive, 4)};'
                f'{_n(arrive, 4)};1"/></circle>')))
            if reaches:
                arrivals.setdefault(reaches, set()).add(round(begin + TRAVEL, 3))
    for node in diagram.nodes:
        for when in sorted(arrivals.get(node.id, ())):
            out.append(_pulse(lay, node.id, when, cycle))
    return out


def _message_spot(lay: Layout, edge: Edge, text: str) -> Point:
    """Where a message's pill sits: the middle of the wire's first band from its
    source, kept inside the diagram."""
    a, b = lay.segments(edge)[0]
    x, y = _at(a, b, 0.5)
    half = _pill_width(text) / 2
    return (min(max(x, MARGIN + half), lay.width - MARGIN - half), y)


def _draw_steps(diagram: Diagram, lay: Layout) -> List[Item]:
    """A narrated flow: each step lights its path, its messages ride their
    wires in turn (a packet, then the label stays), the card a message reaches
    pulses, and the step's sentence shows beneath with a dot for each step.
    Reduced motion shows the first step, still."""
    spans, cycle = _timeline(diagram)
    edge_of = {(e.src, e.dst): e for e in diagram.edges}
    out: List[Item] = []
    placed: Dict[int, List[Tuple[Rect, float, float]]] = {}
    for i, (step, (start, end)) in enumerate(zip(diagram.steps, spans)):
        cls = f"st s{i}"
        lit_from: Dict[Edge, float] = {}
        times = [start + LEAD + j * MESSAGE for j in range(len(step.messages))]
        for j, (m, t) in enumerate(zip(step.messages, times)):
            edge = edge_of.get((m.src, m.dst)) or edge_of[(m.dst, m.src)]
            back = (m.src, m.dst) not in edge_of
            lit_from.setdefault(edge, t)
            later = [times[k] for k in range(j + 1, len(step.messages))
                     if {step.messages[k].src, step.messages[k].dst} == {m.src, m.dst}]
            until = later[0] if later else end
            spot = _message_spot(lay, edge, m.text)
            rect = _pill_rect(spot, _pill_width(m.text))
            for other, a, b in placed.get(i, []):
                if _overlap(rect, other, 2) and t < b and a < until:
                    raise DiagramError(f"{diagram.key}: the message {m.text!r} covers another in its step")
            placed.setdefault(i, []).append((rect, t, until))
            out.append(Item(rect, _pill(spot, m.text, f"msg {cls}", ' opacity="0"',
                                        _visible(t, until, cycle, 0.18))))
            d = lay.path(edge)
            keys = "1;1;0;0" if back else "0;0;1;1"
            out.append(Item(_bbox(lay.wire[edge]), (
                f'<circle class="pkt" r="3.4" opacity="0">'
                f'<animateMotion path="{d}" dur="{_n(cycle)}s" repeatCount="indefinite" calcMode="linear" '
                f'keyPoints="{keys}" keyTimes="0;{_n(t / cycle, 4)};{_n((t + MOVE) / cycle, 4)};1"/>'
                f"{_visible(t, t + MOVE, cycle, 0.08)}</circle>")))
            out.append(_pulse(lay, m.dst, t + MOVE, cycle))
        for edge, t in lit_from.items():
            out.insert(0, Item(_bbox(lay.wire[edge], 2), f'<path class="hl {cls}" d="{lay.path(edge)}" opacity="0">'
                                                         f"{_visible(t, end, cycle, 0.2)}</path>"))
    # The sentences and the step dots, beneath.
    y = lay.footer + 14
    out.append(Item((MARGIN, y, lay.width - MARGIN, y + 1),
                    f'<path class="rule" d="M{MARGIN} {_n(y)}H{lay.width - MARGIN}"/>'))
    first = y + 18 + SAY_LINE * 0.7  # the first line's baseline
    tx = MARGIN + len(diagram.steps) * 14 + 12
    for i, (step, (start, end)) in enumerate(zip(diagram.steps, spans)):
        cx, cy = MARGIN + 4 + i * 14, first - 4.5
        out.append(Item((cx - 4, cy - 4, cx + 4, cy + 4),
                        f'<circle class="dot" cx="{_n(cx)}" cy="{_n(cy)}" r="3.5"/>'
                        f'<circle class="dot on st s{i}" cx="{_n(cx)}" cy="{_n(cy)}" r="3.5" opacity="0">'
                        f"{_visible(start, end, cycle, 0.15)}</circle>"))
        lines = _wrap(step.caption, _say_room(diagram, lay), STEP_SIZE)
        spans_ = "".join(f'<tspan x="{_n(tx)}" y="{_n(first + k * SAY_LINE)}">{_esc(t)}</tspan>'
                         for k, t in enumerate(lines))
        out.append(Item((tx, y, lay.width - MARGIN, lay.height),
                        f'<text class="say st s{i}" opacity="0">{spans_}{_visible(start, end, cycle, 0.25)}</text>'))
    return out


def _draw_legend(diagram: Diagram, lay: Layout) -> List[Item]:
    rows = _legend_rows(diagram, lay.width)
    if not rows:
        return []
    y = lay.footer + 14
    out = [f'<path class="rule" d="M{MARGIN} {_n(y)}H{lay.width - MARGIN}"/>', '<g class="legend">']
    for r, row in enumerate(rows):
        x, mid = float(MARGIN), y + LEGEND_ROW * r + LEGEND_ROW / 2 + 6
        for sample, text in row:
            if sample in DRAWN_KINDS:
                out.append(f'<path class="{_wire_class(sample)}" d="M{_n(x)} {_n(mid)}H{_n(x + 26)}"/>'
                           f'<path class="w" d="M{_n(x + 22)} {_n(mid - 4)}L{_n(x + 28)} {_n(mid)}'
                           f'L{_n(x + 22)} {_n(mid + 4)}"/>')
            elif sample == "product":
                out.append(_chip(x, mid, "PRODUCT"))
            text_x = x + _legend_width(sample, "") - 30
            out.append(f'<text x="{_n(text_x)}" y="{_n(mid + 4)}">{_esc(text)}</text>')
            x += _legend_width(sample, text)
    out.append("</g>")
    return [Item((0, lay.footer, lay.width, lay.height), "".join(out))]


def draw(diagram: Diagram, focus: Optional[str] = None, tiled: bool = False) -> Tuple[Layout, List[Item]]:
    """The diagram laid out, and every element it draws, bottom layer first."""
    if focus is not None and focus not in {n.id for n in diagram.nodes}:
        raise DiagramError(f"{diagram.key}: no node {focus!r} to highlight")
    lay = layout(diagram, title=not tiled)
    _check_fit(diagram, lay)
    on = lit(diagram, focus)
    items: List[Item] = []
    if not tiled:
        title = f"Where {focus} fits" if focus else diagram.title
        items.append(Item((MARGIN, TITLE_Y - 14, MARGIN + _title_width(title), TITLE_Y + 4),
                          f'<text class="title" x="{MARGIN}" y="{TITLE_Y}">{_esc(title.upper())}</text>'))
    items += _draw_wires(diagram, lay, on)
    items += _draw_cards(diagram, lay, on, focus, tiled)
    items += _draw_steps(diagram, lay) if diagram.steps else _draw_wave(diagram, lay, on)
    items += _draw_legend(diagram, lay)
    return lay, items


def _document(theme: str, window: Rect, title: str, desc: str, items: Sequence[Item], frame: bool) -> str:
    x0, y0, x1, y1 = window
    w, h = x1 - x0, y1 - y0
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{_n(w)}" height="{_n(h)}" '
        f'viewBox="{_n(x0)} {_n(y0)} {_n(w)} {_n(h)}" role="img" aria-labelledby="t d">',
        f'<title id="t">{_esc(title)}</title><desc id="d">{_esc(desc)}</desc>',
        f"<style>{_style(THEMES[theme])}</style>",
    ]
    if frame:
        out.append(f'<rect class="card" x="{_n(x0 + .5)}" y="{_n(y0 + .5)}" width="{_n(w - 1)}" '
                   f'height="{_n(h - 1)}" rx="14"/>')
    out += [item.svg for item in items]
    out.append("</svg>")
    return "\n".join(out) + "\n"


def render(diagram: Diagram, theme: str, focus: Optional[str] = None) -> str:
    """The diagram as one standalone SVG document in *theme*, *focus* highlighted."""
    lay, items = draw(diagram, focus)
    title = f"Where {focus} fits" if focus else diagram.title
    return _document(theme, (0, 0, lay.width, lay.height), title, describe(diagram, focus), items, frame=True)


@dataclass(frozen=True)
class Tile:
    """One slice of a tiled diagram: a card and the gaps beside it, a band
    between two rows, or the legend."""

    tag: str
    box: Rect
    node: Optional[str] = None


def tiles(diagram: Diagram, lay: Layout) -> List[List[Tile]]:
    """The slices, a list per line of the README: each row of cards cut in its
    gaps (clear of any link running through or along the gap), each band whole."""
    through: Dict[int, List[float]] = {}  # row -> the x of each link running through it
    for pts in lay.wire.values():
        for i in range(1, len(pts) - 1, 2):
            (x, ya), (_, yb) = pts[i], pts[i + 1]
            row = next(r for r, y in enumerate(lay.row_y) if abs(y - min(ya, yb)) < 0.5)
            through.setdefault(row, []).append(x)
    joined = {(round(a[0], 2), round(b[0], 2), round(a[1], 2)) for a, b in lay.side.values()}
    lines: List[List[Tile]] = []
    last = len(lay.rows) - 1
    for r, row in enumerate(lay.rows):
        y0 = 0.0 if r == 0 else lay.row_y[r]
        y1 = lay.row_y[r] + lay.card_h
        cards = sorted(row, key=lambda n: lay.box[n][0])
        cuts = [0.0]
        for a, b in zip(cards, cards[1:]):
            lo, hi = lay.box[a][0] + lay.card_w, lay.box[b][0]
            if any(abs(x0 - lo) < 0.5 and abs(x1 - hi) < 0.5 for x0, x1, _ in joined):
                cuts.append(hi)  # the link along the gap stays whole, in the left slice
                continue
            busy = sorted(x for x in through.get(r, []) if lo < x < hi)
            spans = list(zip([lo] + busy, busy + [hi]))
            a0, a1 = max(spans, key=lambda s: (s[1] - s[0], -s[0]))
            cuts.append((a0 + a1) / 2)
        cuts.append(float(lay.width))
        lines.append([Tile(f"r{r}-{n}", (cuts[i], y0, cuts[i + 1], y1), n) for i, n in enumerate(cards)])
        if r < last:
            lines.append([Tile(f"band{r}", (0.0, y1, float(lay.width), lay.row_y[r + 1]))])
    lines.append([Tile("legend", (0.0, lay.row_y[last] + lay.card_h, float(lay.width), float(lay.height)))])
    return lines


def render_tiles(diagram: Diagram, theme: str) -> List[Tuple[Tile, str]]:
    """Each slice of the diagram as its own SVG document in *theme*."""
    lay, items = draw(diagram, tiled=True)
    names = {n.id: n for n in diagram.nodes}
    out = []
    for line in tiles(diagram, lay):
        for tile in line:
            keep = [i for i in items if _overlap(i.box, tile.box)]
            title = names[tile.node].name if tile.node else diagram.title
            desc = _tile_alt(diagram, tile) or describe(diagram)
            out.append((tile, _document(theme, tile.box, title, desc, keep, frame=False)))
    return out


def _tile_alt(diagram: Diagram, tile: Tile) -> str:
    if tile.node:
        node = next(n for n in diagram.nodes if n.id == tile.node)
        return f"{node.name}: {node.caption}. {node.blurb}".strip()
    return describe(diagram) if tile.tag == "legend" else ""


