#: Packet seconds: a band takes TRAVEL; each band starts STEP after the one
#: before, so a card pulses as its own packets leave; then a rest.
TRAVEL = STEP = 1.2
REST = 1.4
#: A narrated flow: each message gets MESSAGE seconds, its packet MOVE of them;
#: a step holds until its sentence is read (READ characters a second).
MESSAGE, MOVE, LEAD, HOLD, READ = 1.2, 0.8, 0.4, 1.8, 20.0

Point = Tuple[float, float]
Rect = Tuple[float, float, float, float]  # x0, y0, x1, y1

_NARROW, _WIDE = set("fijlrt.,:;'|!()[]/ -"), set("mwMW@")


def _width(text: str, size: float, mono: bool = True, spacing: float = 0.0) -> float:
    """A rendered width erring wide: the fonts are the viewer's system fonts, so
    nothing can be measured. Monospace is 0.6 em a glyph; a sans is estimated
    per glyph class. *spacing* is the letter-spacing in em."""
    if mono:
        return len(text) * size * (0.6 + spacing)
    em = sum(
        0.36 if c in _NARROW else 0.9 if c in _WIDE else 0.68 if c.isupper() else 0.6
        for c in text
    )
    return (em + spacing * len(text)) * size


def _pill_width(text: str) -> float:
    return _width(text, PILL_SIZE) + 12


def _chip_width(text: str) -> float:
    return _width(text, CHIP_SIZE, spacing=0.06) + 14


def _title_width(text: str) -> float:
    return _width(text.upper(), TITLE_SIZE, spacing=0.08)


def _wrap(text: str, room: float, size: float) -> List[str]:
    """*text* in lines no wider than *room* (sans at *size*), greedily."""
    lines: List[str] = []
    for word in text.split():
        if lines and _width(f"{lines[-1]} {word}", size, mono=False) <= room:
            lines[-1] += f" {word}"
        else:
            lines.append(word)
    return lines


def _curve(a: Point, b: Point) -> Tuple[Point, Point]:
    """The control points of the S-curve from *a* to *b*: upright at both ends."""
    bend = (b[1] - a[1]) / 2
    return (a[0], a[1] + bend), (b[0], b[1] - bend)


def _at(a: Point, b: Point, t: float) -> Point:
    """The point at *t* on the S-curve from *a* to *b*."""
    c1, c2 = _curve(a, b)
    u = 1 - t
    return (
        u ** 3 * a[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * b[0],
        u ** 3 * a[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * b[1],
    )


def _pill_rect(center: Point, width: float) -> Rect:
    return (center[0] - width / 2, center[1] - 9, center[0] + width / 2, center[1] + 9)


def _overlap(a: Rect, b: Rect, pad: float = 0.0) -> bool:
    return a[0] < b[2] + pad and a[2] > b[0] - pad and a[1] < b[3] + pad and a[3] > b[1] - pad


def _bbox(points: Sequence[Point], pad: float = 0.0) -> Rect:
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return (min(xs) - pad, min(ys) - pad, max(xs) + pad, max(ys) + pad)


def _segment_path(a: Point, b: Point) -> str:
    c1, c2 = _curve(a, b)
    return f"M{_n(a[0])} {_n(a[1])}C{_n(c1[0])} {_n(c1[1])} {_n(c2[0])} {_n(c2[1])} {_n(b[0])} {_n(b[1])}"


# ------------------------------------------------------------------ layout
@dataclass
class Layout:
    width: int
    height: int
    card_w: float
    card_h: float
    rows: List[List[str]]  # display rows, top first, each left to right
    row_y: List[float]  # the top of each display row
    box: Dict[str, Point]  # node -> its card's top-left corner
    #: Each link between rows: its waypoints, from its source port to its target
    #: port, two per row it runs through. Consecutive points across a band are
    #: S-curves; within a row, an upright line.
    wire: Dict[Edge, List[Point]]
    #: Each link within a row (an Edge or a Pair): its left and right ends.
    side: Dict[object, Tuple[Point, Point]]
    label: Dict[Edge, Point]  # the pill centre of each labelled link between rows
    footer: float  # where the legend or the step sentences start
    title: bool

    def row_of(self, node: str) -> int:
        return next(i for i, row in enumerate(self.rows) if node in row)

    def rect(self, node: str) -> Rect:
        x, y = self.box[node]
        return (x, y, x + self.card_w, y + self.card_h)

    def segments(self, edge: Edge) -> List[Tuple[Point, Point]]:
        """The wire's crossings of the bands, in order from its source."""
        pts = self.wire[edge]
        return [(pts[i], pts[i + 1]) for i in range(0, len(pts) - 1, 2)]

    def path(self, edge: Edge) -> str:
        if edge in self.side:
            (x0, y), (x1, _) = self.side[edge]
            return f"M{_n(x0)} {_n(y)}H{_n(x1)}"
        pts = self.wire[edge]
        d = f"M{_n(pts[0][0])} {_n(pts[0][1])}"
        for i in range(1, len(pts)):
            a, b = pts[i - 1], pts[i]
            if i % 2:  # across a band
                c1, c2 = _curve(a, b)
                d += f"C{_n(c1[0])} {_n(c1[1])} {_n(c2[0])} {_n(c2[1])} {_n(b[0])} {_n(b[1])}"
            else:  # through a row
                d += f"V{_n(b[1])}"
        return d


def _ranks(diagram: Diagram) -> Dict[str, int]:
    """Each node's rank: one past its highest parent (an opened product sets no
    rank); the diagram's ``top`` nodes all take the highest."""
    order = {n.id: i for i, n in enumerate(diagram.nodes)}
    parents: Dict[str, List[str]] = {n.id: [] for n in diagram.nodes}
    for edge in diagram.edges:
        if edge.src not in order or edge.dst not in order:
            raise DiagramError(f"{diagram.key}: edge {edge.src} -> {edge.dst} names an unknown node")
        if edge.kind != "opens":
            parents[edge.dst].append(edge.src)
    for pair in diagram.pairs:
        if pair.a not in order or pair.b not in order:
            raise DiagramError(f"{diagram.key}: pair {pair.a} - {pair.b} names an unknown node")
    rank: Dict[str, int] = {}

    def rank_of(node: str, trail: Tuple[str, ...] = ()) -> int:
        if node in trail:
            raise DiagramError(f"{diagram.key}: cycle through {' -> '.join(trail + (node,))}")
        if node not in rank:
            rank[node] = 1 + max((rank_of(p, trail + (node,)) for p in parents[node]), default=-1)
        return rank[node]

    for node in diagram.nodes:
        rank_of(node.id)
    peak = max(rank.values())
    for node in diagram.top:
        rank[node] = peak
    for edge in diagram.edges:
        if edge.kind != "opens" and rank[edge.src] >= rank[edge.dst]:
            raise DiagramError(f"{diagram.key}: {edge.src} -> {edge.dst} runs against the ranks")
    for pair in diagram.pairs:
        if rank[pair.a] != rank[pair.b]:
            raise DiagramError(f"{diagram.key}: {pair.a} and {pair.b} must share a row")
    return rank


def _card_h(diagram: Diagram) -> float:
    room = diagram.card_w - 32
    lines = max((len(_wrap(n.blurb, room, BLURB_SIZE)) for n in diagram.nodes if n.blurb), default=0)
    return H_HEAD if not lines else BLURB_TOP + (lines - 1) * BLURB_LINE + BLURB_PAD


def _link_gap(label: str) -> float:
    return max(GAP, _pill_width(label) + 2 * LINK_PAD)


def _place(rows: List[List[str]], neighbours: Dict[str, List[str]], gap: Callable[[str, str], float],
           card_w: float) -> Dict[str, float]:
    """Each card's centre x. A row of several cards is centred, so the rows
    stack symmetrically; a lone card sits at the mean of its neighbours placed
    before it, working out from the widest row (with none, centred)."""

    def centred(row: List[str]) -> List[float]:
        xs, x = [], 0.0
        for i, n in enumerate(row):
            if i:
                x += card_w + gap(row[i - 1], n)
            xs.append(x)
        mid = (xs[0] + xs[-1]) / 2
        return [v - mid for v in xs]

    widths = [centred(r)[-1] - centred(r)[0] for r in rows]
    widest = widths.index(max(widths))
    x: Dict[str, float] = dict(zip(rows[widest], centred(rows[widest])))
    for r in list(range(widest - 1, -1, -1)) + list(range(widest + 1, len(rows))):
        row = rows[r]
        default = centred(row)
        if len(row) > 1:
            x.update(zip(row, default))
            continue
        seen = [x[m] for m in neighbours[row[0]] if m in x]
        x[row[0]] = sum(seen) / len(seen) if seen else 0.0
    return x


def _crossings(lines: List[Tuple[str, str, Point, Point]]) -> int:
    def ccw(a: Point, b: Point, c: Point) -> float:
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])

    count = 0
    for (s1, d1, a, b), (s2, d2, c, d) in itertools.combinations(lines, 2):
        if {s1, d1} & {s2, d2}:
            continue
        if ccw(a, b, c) * ccw(a, b, d) < 0 and ccw(c, d, a) * ccw(c, d, b) < 0:
            count += 1
    return count


def layout(diagram: Diagram, title: bool = True) -> Layout:
    """Rows by rank; each row's order the one with fewest crossings (then the
    shortest links, then the declared order); a link that skips a row runs
    through the gap there nearest its straight line, clear of the cards."""
    rank = _ranks(diagram)
    order = {n.id: i for i, n in enumerate(diagram.nodes)}
    count = max(rank.values()) + 1
    by_rank: List[List[str]] = [[] for _ in range(count)]
    for node in diagram.nodes:
        by_rank[rank[node.id]].append(node.id)
    rows = list(reversed(by_rank)) if diagram.upward else by_rank
    row_index = {n: i for i, row in enumerate(rows) for n in row}

    # Links within a row (pairs, and an opened product beside its opener).
    inline: List[Tuple[object, str, str, str]] = [(p, p.a, p.b, p.label) for p in diagram.pairs]
    inline += [(e, e.src, e.dst, e.label) for e in diagram.edges if row_index[e.src] == row_index[e.dst]]
    joined = {frozenset((a, b)): label for _, a, b, label in inline}
    across = [e for e in diagram.edges if row_index[e.src] != row_index[e.dst]]
    neighbours: Dict[str, List[str]] = {n.id: [] for n in diagram.nodes}
    for e in across:
        neighbours[e.src].append(e.dst)
        neighbours[e.dst].append(e.src)

    def gap(a: str, b: str) -> float:
        label = joined.get(frozenset((a, b)))
        return GAP if label is None else _link_gap(label)

    def adjacent(row: Sequence[str]) -> bool:
        spot = {n: i for i, n in enumerate(row)}
        return all(abs(spot[a] - spot[b]) == 1 for _, a, b, _ in inline if a in spot)

    options = []
    for row in rows:
        perms = [list(p) for p in itertools.permutations(row) if adjacent(p)]
        if not perms:
            raise DiagramError(f"{diagram.key}: the links within row {row} cannot all join neighbours")
        options.append(perms)
    best = None
    for choice in itertools.product(*options):
        xs = _place(list(choice), neighbours, gap, diagram.card_w)
        lines = [(e.src, e.dst, (xs[e.src], row_index[e.src]), (xs[e.dst], row_index[e.dst])) for e in across]
        blocked = 0
        for e in across:
            lo, hi = sorted((row_index[e.src], row_index[e.dst]))
            for r in range(lo + 1, hi):
                t = (r - row_index[e.src]) / (row_index[e.dst] - row_index[e.src])
                x = xs[e.src] + (xs[e.dst] - xs[e.src]) * t
                blocked += any(abs(x - xs[n]) < diagram.card_w / 2 + CLEARANCE for n in choice[r])
        cost = (_crossings(lines) + blocked, round(sum(abs(a[0] - b[0]) for *_, a, b in lines), 3))
        if best is None or cost < best[0]:
            best = (cost, [list(r) for r in choice], xs)
    _, rows, xc = best

    card_w, card_h = diagram.card_w, _card_h(diagram)
    top = TITLE_BAND if title else TOP_PAD
    row_y = [top + i * (card_h + BAND) for i in range(len(rows))]
    row_index = {n: i for i, row in enumerate(rows) for n in row}

    def left(n: str) -> float:
        return xc[n] - card_w / 2

    # Route each link that skips a row through that row.
    channels: Dict[Edge, List[float]] = {}
    used: Dict[Tuple[int, float], int] = {}
    for edge in sorted(across, key=lambda e: (min(row_index[e.src], row_index[e.dst]), order[e.src], order[e.dst])):
        rs, rd = row_index[edge.src], row_index[edge.dst]
        step = 1 if rd > rs else -1
        hops = []
        for r in range(rs + step, rd, step):
            want = xc[edge.src] + (xc[edge.dst] - xc[edge.src]) * (r - rs) / (rd - rs)
            cards = sorted(rows[r], key=lambda n: xc[n])
            lanes = [left(cards[0]) - CHANNEL, left(cards[-1]) + card_w + CHANNEL]
            closed = []  # the gaps a link along the row already runs through
            for a, b in zip(cards, cards[1:]):
                if frozenset((a, b)) in joined:
                    closed.append((left(a) + card_w - CLEARANCE, left(b) + CLEARANCE))
                else:
                    lanes.append((left(a) + card_w + left(b)) / 2)
            if all(abs(want - xc[n]) >= card_w / 2 + CLEARANCE for n in cards) and not any(
                    lo <= want <= hi for lo, hi in closed):
                lanes.append(want)
            lane = min(lanes, key=lambda v: (abs(v - want), v))
            nudge = used.get((r, round(lane, 2)), 0)
            used[(r, round(lane, 2))] = nudge + 1
            hops.append(lane + nudge * PORT_STEP)
        channels[edge] = hops

    # Spread each face's ports by where their links head.
    def toward(edge: Edge, node: str) -> float:
        hops = channels[edge]
        if node == edge.src:
            return hops[0] if hops else xc[edge.dst]
        return hops[-1] if hops else xc[edge.src]

    port: Dict[Tuple[Edge, str], float] = {}
    for node in diagram.nodes:
        for face_up in (True, False):
            mine = [e for e in across if node.id in (e.src, e.dst)
                    and (row_index[e.dst if e.src == node.id else e.src] < row_index[node.id]) == face_up]
            mine.sort(key=lambda e: (toward(e, node.id), order[e.src], order[e.dst]))
            step = min(PORT_STEP, (card_w - 40) / max(len(mine) - 1, 1))
            for i, e in enumerate(mine):
                port[(e, node.id)] = xc[node.id] + (i - (len(mine) - 1) / 2) * step

    def face(node: str, up: bool) -> float:
        y = row_y[row_index[node]]
        return y if up else y + card_h

    wire: Dict[Edge, List[Point]] = {}
    for edge in across:
        rs, rd = row_index[edge.src], row_index[edge.dst]
        up = rd < rs
        pts = [(port[(edge, edge.src)], face(edge.src, up))]
        for r, x in zip(range(rs + (-1 if up else 1), rd, -1 if up else 1), channels[edge]):
            y0, y1 = row_y[r], row_y[r] + card_h
            pts += [(x, y1), (x, y0)] if up else [(x, y0), (x, y1)]
        pts.append((port[(edge, edge.dst)], face(edge.dst, not up)))
        wire[edge] = pts

    side: Dict[object, Tuple[Point, Point]] = {}
    for key, a, b, _ in inline:
        a, b = sorted((a, b), key=lambda n: xc[n])
        y = row_y[row_index[a]] + card_h / 2
        side[key] = ((left(a) + card_w, y), (left(b), y))

    # Labels on links between rows: the first band from the source, the first
    # spot clear of the labels already placed.
    label: Dict[Edge, Point] = {}
    taken: List[Rect] = []
    for edge in across:
        if not edge.label:
            continue
        a, b = wire[edge][0], wire[edge][1]
        width = _pill_width(edge.label)
        for t in (0.5, 0.35, 0.65, 0.25, 0.75):
            spot = _at(a, b, t)
            if not any(_overlap(_pill_rect(spot, width), r, 4) for r in taken):
                break
        else:
            raise DiagramError(f"{diagram.key}: no room for the label {edge.label!r} on {edge.src} -> {edge.dst}")
        label[edge] = spot
        taken.append(_pill_rect(spot, width))

    # Fit the canvas to what was placed, then shift it all into view.
    xs = [left(n) for n in xc] + [left(n) + card_w for n in xc]
    xs += [x for hops in channels.values() for x in hops]
    xs += [r[0] for r in taken] + [r[2] for r in taken]
    lo, hi = min(xs) - MARGIN, max(xs) + MARGIN
    need = MARGIN * 2 + (_title_width(diagram.title) if title else 0)
    if hi - lo < need:
        lo -= (need - (hi - lo)) / 2
        hi = lo + need
    dx = -lo
    box = {n: (left(n) + dx, row_y[row_index[n]]) for n in xc}
    wire = {e: [(x + dx, y) for x, y in pts] for e, pts in wire.items()}
    side = {k: ((a[0] + dx, a[1]), (b[0] + dx, b[1])) for k, (a, b) in side.items()}
    label = {e: (x + dx, y) for e, (x, y) in label.items()}
    width = int(round(hi - lo))
    footer = row_y[-1] + card_h
    lay = Layout(width, 0, card_w, card_h, rows, row_y, box, wire, side, label, footer, title)
    lay.height = int(round(footer + _footer_height(diagram, lay) + BOTTOM))
    return lay


