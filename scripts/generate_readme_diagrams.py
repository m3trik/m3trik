# ------------------------------------------------------------------ measuring
def _script(name: str):
    if str(SCRIPTS) not in sys.path:
        sys.path.insert(0, str(SCRIPTS))
    return __import__(name)


def _names(requirements: Sequence[str]) -> List[str]:
    pattern = _script("check_layers").REQUIREMENT_NAME
    names = []
    for requirement in requirements:
        match = pattern.match(requirement.strip())
        if match:
            names.append(match.group(0).split("[")[0].lower().replace("-", "_"))
    return names


def _projects(workspace: Path, packages: Sequence[str]) -> Dict[str, dict]:
    layers = _script("check_layers")
    return {pkg: layers.pyproject(workspace / pkg).get("project", {}) for pkg in packages}


def ecosystem_edges(workspace: Path, packages: Sequence[str], products: Sequence[str]) -> List[Edge]:
    """Every ecosystem link the packages' pyprojects declare, dependency first."""
    projects = _projects(workspace, packages)
    # A dependency names a distribution; the node is the package that ships it.
    unit_of = {pkg: pkg for pkg in packages}
    for pkg, project in projects.items():
        if project.get("name"):
            unit_of[project["name"].lower().replace("-", "_")] = pkg
    edges = []
    for pkg in packages:
        project = projects[pkg]
        required = {unit_of[n] for n in _names(project.get("dependencies", [])) if n in unit_of}
        extras: Dict[str, str] = {}
        for extra, requirements in sorted(project.get("optional-dependencies", {}).items()):
            for name in _names(requirements):
                if name in unit_of:
                    extras.setdefault(unit_of[name], extra)
        for dep in packages:
            if dep == pkg:
                continue
            if dep in required:
                edges.append(Edge(dep, pkg, "requires"))
            elif dep in extras:
                kind = "opens" if dep in products else "extra"
                edges.append(Edge(dep, pkg, kind, f"[{extras[dep]}]"))
    return edges


def reduce_edges(edges: Sequence[Edge]) -> List[Edge]:
    """*edges* without each link that a longer path of required links implies.

    Only a required link implies anything: what an install extra brings, a plain
    install does not, and an opened product is never imported at all.
    """
    required: Dict[str, List[str]] = {}
    for edge in edges:
        if edge.kind == "requires":
            required.setdefault(edge.src, []).append(edge.dst)

    def implied(edge: Edge) -> bool:
        stack = [n for n in required.get(edge.src, ()) if n != edge.dst]
        seen = set(stack)
        while stack:
            node = stack.pop()
            if node == edge.dst:
                return True
            for nxt in required.get(node, ()):
                if nxt not in seen:
                    seen.add(nxt)
                    stack.append(nxt)
        return False

    return [e for e in edges if e.kind == "opens" or not implied(e)]


def ecosystem(workspace: Path = WORKSPACE) -> Diagram:
    """The ecosystem packages and their declared links, implied ones left out."""
    sw = _script("sync_workspace")
    data = sw.load(workspace / "m3trik" / "workspace.json")
    packages = sw.ecosystem_packages(data)
    products = sw.products(data)
    missing = [p for p in packages if p not in CARDS]
    if missing:
        raise DiagramError(
            f"no card for {', '.join(missing)}: add a row to CARDS in {Path(__file__).name}"
        )
    projects = _projects(workspace, packages)
    nodes = []
    for pkg in packages:
        caption, icon, blurb = CARDS[pkg]
        urls = projects[pkg].get("urls", {})
        link = "" if pkg in UNLINKED else urls.get("Repository") or urls.get("Homepage") or ""
        nodes.append(Node(pkg, pkg, caption, icon, product=pkg in products, blurb=blurb,
                          link=link, tip=projects[pkg].get("description", "")))
    edges = reduce_edges(ecosystem_edges(workspace, packages, products))
    edges.sort(key=lambda e: (packages.index(e.src), packages.index(e.dst)))  # reads foundation first
    pairs, seen = [], set()
    for a, b in sw.twins(data).items():
        if a in packages and b in packages and frozenset((a, b)) not in seen:
            seen.add(frozenset((a, b)))
            first, second = sorted((a, b), key=packages.index)
            pairs.append(Pair(first, second, "same API"))
    return Diagram("ecosystem", "The ecosystem", nodes, edges, pairs, list(ECOSYSTEM_LEGEND),
                   upward=True, top=tuple(p for p in packages if p in products), card_w=290)


