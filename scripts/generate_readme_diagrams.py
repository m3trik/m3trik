@dataclass
class Lit:
    """What a highlighted diagram keeps at full strength."""

    nodes: Set[str]
    edges: Set[Edge]
    pairs: Set[Pair]


def lit(diagram: Diagram, focus: Optional[str]) -> Lit:
    """Without *focus*, everything. With it: *focus*, its pair, and each path
    through it -- what it builds on (upstream) and what builds on it -- with
    any pair both of whose cards that lights."""
    if focus is None:
        return Lit({n.id for n in diagram.nodes}, set(diagram.edges), set(diagram.pairs))

    def closure(forward: bool) -> Set[str]:
        found, stack = {focus}, [focus]
        while stack:
            node = stack.pop()
            for e in diagram.edges:
                src, dst = (e.src, e.dst) if forward else (e.dst, e.src)
                if src == node and dst not in found:
                    found.add(dst)
                    stack.append(dst)
        return found

    down, up = closure(True), closure(False)
    edges = {e for e in diagram.edges if {e.src, e.dst} <= up or {e.src, e.dst} <= down}
    nodes = up | down | {n for p in diagram.pairs if focus in (p.a, p.b) for n in (p.a, p.b)}
    pairs = {p for p in diagram.pairs if {p.a, p.b} <= nodes}
    return Lit(nodes, edges, pairs)


def _and(names: Sequence[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def describe(diagram: Diagram, focus: Optional[str] = None) -> str:
    """The text alternative: every link, pair and product as a sentence, or a
    narrated flow's steps in order."""
    if diagram.desc:
        body = diagram.desc
    elif diagram.steps:
        body = f"{diagram.title}: " + " ".join(f"({i}) {s.caption}" for i, s in enumerate(diagram.steps, 1))
    else:
        names = {n.id: n.name for n in diagram.nodes}
        clauses = [
            PHRASES[e.kind].format(src=names[e.src], dst=names[e.dst], label=e.label)
            for e in diagram.edges
        ]
        clauses += [f"{names[p.a]} and {names[p.b]} share a mirrored API" for p in diagram.pairs]
        body = f"{diagram.title}: " + "; ".join(clauses) + "."
        products = [n.name for n in diagram.nodes if n.product]
        if products:
            verb = "is a product" if len(products) == 1 else "are products"
            body += f" {_and(products)} {verb}, which nothing imports."
    if focus:
        return f"{focus} (highlighted) in {body[0].lower()}{body[1:]}"
    return body


def _legend_width(sample: str, text: str) -> float:
    lead = 38 if sample in DRAWN_KINDS else _chip_width("PRODUCT") + 10 if sample == "product" else 0
    return lead + _width(text, LEGEND_SIZE) + 30


def _legend_rows(diagram: Diagram, width: float) -> List[List[Tuple[str, str]]]:
    rows: List[List[Tuple[str, str]]] = [[]]
    used = 0.0
    for sample, text in diagram.legend:
        w = _legend_width(sample, text)
        if rows[-1] and MARGIN + used + w - 30 > width - MARGIN:
            rows.append([])
            used = 0.0
        rows[-1].append((sample, text))
        used += w
    return rows if diagram.legend else []


def _say_room(diagram: Diagram, lay: Layout) -> float:
    """How wide a step's sentence may run: past the step dots."""
    return lay.width - 2 * MARGIN - len(diagram.steps) * 14 - 12


def _footer_height(diagram: Diagram, lay: Layout) -> float:
    if diagram.steps:
        return 14 + 18 + SAY_LINES * SAY_LINE
    if diagram.legend:
        return 14 + len(_legend_rows(diagram, lay.width)) * LEGEND_ROW
    return 0.0


def _timeline(diagram: Diagram) -> Tuple[List[Tuple[float, float]], float]:
    """Each step's (start, end) in seconds, and the whole loop."""
    spans, t = [], 0.0
    for step in diagram.steps:
        length = max(LEAD + len(step.messages) * MESSAGE + HOLD, len(step.caption) / READ)
        spans.append((t, t + length))
        t += length
    return spans, t


def _check_fit(diagram: Diagram, lay: Layout) -> None:
    card_w = diagram.card_w
    for node in diagram.nodes:
        if node.icon not in ICONS:
            raise DiagramError(f"{diagram.key}: {node.id} names no known icon ({node.icon!r})")
        reserve = (_chip_width("PRODUCT") + 8 if node.product else 0) + (22 if node.link else 0)
        if _width(node.name, NAME_SIZE, mono=False) > card_w - TEXT_X - 10 - reserve:
            raise DiagramError(f"{diagram.key}: {node.name!r} on {node.id} is wider than its box: shorten it")
        if _width(node.caption, CAPTION_SIZE) > card_w - TEXT_X - 10:
            raise DiagramError(f"{diagram.key}: {node.caption!r} on {node.id} is wider than its box: shorten it")
        if len(_wrap(node.blurb, card_w - 32, BLURB_SIZE)) > BLURB_LINES:
            raise DiagramError(f"{diagram.key}: the sentence on {node.id} runs past {BLURB_LINES} lines: shorten it")
    ids = {n.id for n in diagram.nodes}
    for step in diagram.steps:
        if len(_wrap(step.caption, _say_room(diagram, lay), STEP_SIZE)) > SAY_LINES:
            raise DiagramError(f"{diagram.key}: the step {step.caption[:30]!r}... runs past {SAY_LINES} lines")
        for m in step.messages:
            along = [e for e in diagram.edges if {e.src, e.dst} == {m.src, m.dst}]
            if not {m.src, m.dst} <= ids or not along or along[0] not in lay.wire:
                raise DiagramError(f"{diagram.key}: the message {m.text!r} runs along no link between rows")
            if _pill_width(m.text) > lay.width - 2 * MARGIN:
                raise DiagramError(f"{diagram.key}: the message {m.text!r} is wider than the diagram")


