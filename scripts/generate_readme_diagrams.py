"""Draw the READMEs' diagrams from what the workspace declares.

A README that ships to PyPI cannot use Mermaid (PyPI shows it as a code block),
and a hand-drawn picture drifts from the code it describes. So the diagrams are
generated: SVG files under ``m3trik/docs/diagrams/``, one light and one dark per
diagram, embedded by absolute URL so GitHub and PyPI both render them, with
GitHub picking the theme through ``<picture>`` (PyPI keeps the light one).

**Weighed** (CODE_STANDARD section 15): Graphviz (``dot -Tsvg``), mermaid-cli
(Mermaid rendered to a static SVG) and D2 each draw a graph, and each needs a
binary or a Node and headless-Chromium install in CI, writes output that
changes with its version, and has no notion of a highlighted package, a
light/dark pair, a card that links, or a narrated sequence. ``api.search``
finds nothing internal. The layout here is small (layered rows, links routed
through the gaps), stdlib-only and byte-deterministic, so it is built.

**Where the facts come from.** The ecosystem diagram is measured, never listed:
its packages are ``workspace.json``'s ecosystem set, its links each package's
``pyproject.toml`` dependencies (a ``dependencies`` entry is required, an
``optional-dependencies`` one an install extra, and an extra naming a product
is opened by name, never imported), its mirrored pair the manifest's ``twin``,
and each card's link and tooltip the pyproject's ``Repository`` URL and
``description``. A link is left out when a path of required links already
implies it (a path through an extra implies nothing: a plain install does not
take the extra). What cannot be measured is declared below: each card's
caption, icon and sentence (:data:`CARDS`), the repos a public README may not
link yet (:data:`UNLINKED`) and the hand-specified flows (:data:`FLOWS`).

**How they read.** Cards in rows, each a rank of the longest path to it. The
ecosystem builds upward: the core at the bottom, the products (which nothing
imports) on top. A flow reads downward, and may be narrated: its steps light
one path at a time, each message a label riding its wire, the step's sentence
beneath. A link that skips a row runs through a gap in it; two cards a link
joins within one row sit side by side.

**Where they go.** A README asks for one with a marker pair; this fills it::

    <!-- diagram:ecosystem -->             every package, each card its own
                                           linked image (GitHub: the m3trik README)
    <!-- diagram:ecosystem/mayatk -->      one image, mayatk highlighted, linked
                                           to the whole ecosystem
    <!-- diagram:one-api -->               a flow from FLOWS
    <!-- /diagram:<the same name> -->

The tiled form gives each card a link and a tooltip, which an image cannot
carry: a row of images, each a slice of one drawing, lines up because every
slice keeps the drawing's scale (``width`` as a share of the row) and sits on
the line's top (``align="top"``). Motion stays within a slice, so slices that
load apart never show a seam in it. PyPI pages take the one-image form.

The README text between the markers is generated: never edit it. A marker in a
code span or fence is text, not a request; a malformed one is refused. Only
the variants some README asks for are drawn. An SVG no README asks for is
reported and kept, because a released PyPI page embeds its URL for good;
``--prune`` deletes it.

Usage:
    python generate_readme_diagrams.py            # write the SVGs and README blocks
    python generate_readme_diagrams.py --check    # report drift; write nothing
    python generate_readme_diagrams.py --prune    # write, and delete unused SVGs

Exit: 0 in sync (or written), 1 drift, 2 could not run (an unknown diagram or a
malformed marker, text that does not fit its box, a dependency cycle, a link
with no gap to run through, a missing pyproject).
"""

