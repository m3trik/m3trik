"""Generate the C# names of pythontk's job-queue layout -- and fail when they drift.

pythontk's ``JobQueue`` is a folder of JSON jobs one worker takes in order (no
port): its file names and the heartbeat's states are declared once there, as
data (``WORKER``, ``STOP``, ``LEASE``, ``SUFFIXES``, ``WORKER_STATES``). A Unity
editor serves the same protocol in C#, so its names are generated here, never
retyped: extapps' Unity Scripts package (``unity_scripts/unity_package``) and
unitytk's kernel (``Kernel/Editor``, whose session server serves the queue)
each read ``QueueLayout`` from a file this writes in its own namespace. The
Unity Scripts package is copied into a project as an embedded package, whose
``.meta`` files Unity makes itself, so none is written for it; unitytk ships
every file with its ``.meta``, so its file gets one. Held by
``check_csharp.py`` (its ``GENERATORS``) as well as by ``--check``.

Usage::

    python sync_job_queue.py           # write the generated files
    python sync_job_queue.py --check   # exit 1 when it is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List, Tuple

SCRIPTS = Path(__file__).resolve().parent
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import sync_scene_records as records  # noqa: E402  (the shared sync_text)

REPO_ROOT = records.REPO_ROOT
#: The generated file, in extapps' Unity Scripts package.
TARGET = (
    REPO_ROOT / "extapps" / "extapps" / "unity_scripts" / "unity_package" / "Editor" / "QueueLayout.g.cs"
)
NAMESPACE = "M3trik.UnityScripts"
#: The generated file in unitytk's kernel, whose session server serves the queue.
#: The package ships every file with its ``.meta``, so this one has one too.
UNITYTK_TARGET = (
    REPO_ROOT / "unitytk" / "com.m3trik.unitytk" / "Kernel" / "Editor" / "QueueLayout.g.cs"
)
UNITYTK_NAMESPACE = "M3trik.Unitytk.Kernel"
#: What the file opens with -- the reader's cue not to edit it.
GENERATED = (
    "GENERATED by m3trik/scripts/sync_job_queue.py from pythontk's JobQueue\n"
    "// -- do not edit; run the script after changing the queue's layout."
)


def _job_queue():
    """``JobQueue`` from the sibling pythontk checkout (not an installed copy)."""
    records._records()  # puts the checkout on sys.path
    from pythontk import JobQueue

    return JobQueue


def _pascal(name: str) -> str:
    return "".join(part.title() for part in name.split("_"))


def render(namespace: str = NAMESPACE) -> str:
    """The C# file in *namespace*, from the queue's declared layout."""
    queue = _job_queue()
    lines = [
        "// <auto-generated>",
        f"// {GENERATED}",
        "// </auto-generated>",
        "",
        f"namespace {namespace}",
        "{",
        "    /// <summary>pythontk JobQueue's file layout: what a worker names its",
        "    /// files and heartbeat states, as the Python caller reads them.</summary>",
        "    internal static class QueueLayout",
        "    {",
        "        /// <summary>The worker's heartbeat file.</summary>",
        f'        public const string Worker = "{queue.WORKER}";',
        "        /// <summary>A request to end after the current job.</summary>",
        f'        public const string Stop = "{queue.STOP}";',
        "        /// <summary>How long a caller still wants the worker.</summary>",
        f'        public const string Lease = "{queue.LEASE}";',
    ]
    for state, suffix in queue.SUFFIXES.items():
        lines.append(f"        /// <summary>A {state} job's file suffix, <c>&lt;id&gt;{suffix}</c>.</summary>")
        lines.append(f'        public const string {_pascal(state)} = "{suffix}";')
    for state in queue.WORKER_STATES:
        lines.append(f"        /// <summary>The heartbeat's <c>{state}</c> state.</summary>")
        lines.append(f'        public const string State{_pascal(state)} = "{state}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def targets() -> List[Tuple[Path, str]]:
    """``[(path, text)]``: extapps' file (no ``.meta``: see the module docstring),
    then unitytk's kernel's and its ``.meta``, its GUID derived from its name."""
    return [
        (TARGET, render()),
        (UNITYTK_TARGET, render(UNITYTK_NAMESPACE)),
        (
            UNITYTK_TARGET.with_name(UNITYTK_TARGET.name + ".meta"),
            records.script_cs_meta(f"{UNITYTK_NAMESPACE}.QueueLayout"),
        ),
    ]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 on drift")
    args = parser.parse_args(argv)
    failed = False
    for path, text in targets():
        failed |= records.sync_text(path, text, args.check, "job-queue layout", "sync_job_queue.py")
    if not failed:
        print("in sync: the job-queue layout")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
