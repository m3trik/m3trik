"""Generate unitytk's C# operation contract from pythontk's payloads -- and fail when it drifts.

pythontk declares the payloads every runner of an operation reads and writes
once, as ``SchemaSpec`` dataclasses: ``OpRequest`` (a call), ``Outcome``
(``Change``, ``Issue``, ``OpCall``: what it hands back), and ``OperationEntry``
/ ``OperationCatalogDocument`` (a catalog). The Unity kernel speaks the same
contract in C#, so its types are generated here, one ``<Type>.g.cs`` per
payload in the folder of unitytk's core assembly (``M3trik.Unitytk.Core``,
no engine references; found under the package root unitytk's pyproject
declares), each reading a parsed JSON tree as pythontk validates and
writing one back, plus their shared conversions (``Wire.g.cs``) -- the
readers' half is ``sync_scene_records.py``'s, so a record and a contract read
alike. Each file ships with a ``.meta`` whose GUID is derived from its type's
name, so regenerating never mints a new one.

Usage::

    python sync_operation_contract.py           # write the generated files
    python sync_operation_contract.py --check   # exit 1 when one is stale
"""

from __future__ import annotations

import argparse
import json
import sys
import uuid
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import sync_scene_records as records  # noqa: E402  (its readers, wrapping and sync)

REPO_ROOT = records.REPO_ROOT
NAMESPACE = "M3trik.Unitytk.Core"
#: The namespace each generated type's ``.meta`` GUID is derived in.
GUID_NAMESPACE = "https://github.com/m3trik/unitytk/contract/"
#: What every generated file opens with -- the reader's cue not to edit it.
GENERATED = (
    "GENERATED by m3trik/scripts/sync_operation_contract.py from pythontk's "
    "operation payloads -- do not edit; run the script after changing one."
)
#: The payloads, by the module pythontk declares them in.
PAYLOADS = (
    ("outcome", ("OpRequest", "Outcome", "Change", "Issue", "OpCall")),
    ("operation", ("OperationEntry", "OperationCatalogDocument")),
)

#: The writers' half of ``Wire``: a payload as the JSON tree ``Json.Write`` writes.
CS_WIRE_WRITE = """\

    // A field into a JSON tree: set ones only, as pythontk writes no None.
    public static void Put(IDictionary<string, object> o, string key, object value)
    {
        if (value != null) o[key] = value;
    }

    // A list of payloads as a list of their trees; null stays null.
    public static List<object> Trees<T>(List<T> items, Func<T, object> tree)
    {
        if (items == null) return null;
        var list = new List<object>(items.Count);
        foreach (T item in items) list.Add(item == null ? null : tree(item));
        return list;
    }
"""


def _payloads() -> dict:
    """``{name: payload class}`` from the sibling pythontk checkout."""
    records._records()  # puts the checkout on sys.path
    import importlib

    found = {}
    for module, names in PAYLOADS:
        mod = importlib.import_module(f"pythontk.core_utils.operation_catalog.{module}")
        for name in names:
            found[name] = getattr(mod, name)
    return found


def _member(key: str, node: dict, payloads) -> tuple:
    """``(C# type, read expression over o, tree expression of the field)``."""
    field = f"@{key}" if key in records.CS_KEYWORDS else key
    if "anyOf" in node:
        options = [n for n in node["anyOf"] if n.get("type") != "null"]
        node = options[0] if len(options) == 1 else {}
    if "$ref" in node:
        cls = node["$ref"].rsplit("/", 1)[-1]
        assert cls in payloads, f"{key}: {cls} is no payload generated here"
        return cls, f'Wire.Obj(o, "{key}", {cls}.Read)', f"{field}?.ToJson()"
    kind = node.get("type")
    if kind == "array":
        item = node.get("items", {})
        if "$ref" in item:
            cls = item["$ref"].rsplit("/", 1)[-1]
            assert cls in payloads, f"{key}: {cls} is no payload generated here"
            return (
                f"List<{cls}>",
                f'Wire.Objs(o, "{key}", {cls}.Read)',
                f"Wire.Trees({field}, item => item.ToJson())",
            )
        if item.get("type") == "string":
            return "List<string>", f'Wire.Strs(o, "{key}")', field
        return "IList<object>", f'Wire.Elements(o, "{key}")', field
    simple = {
        "string": ("string", "Str"),
        "integer": ("int?", "Int"),
        "number": ("double?", "Num"),
        "boolean": ("bool?", "Bool"),
    }
    if kind in simple:
        cs, reader = simple[kind]
        return cs, f'Wire.{reader}(o, "{key}")', field
    if kind == "object":
        return "IDictionary<string, object>", f'Wire.Dict(o, "{key}")', field
    return "object", f'Wire.Get(o, "{key}")', field


def _header(about: str) -> list:
    lines = ["// <auto-generated>"]
    lines += [f"// {line}" for line in records._wrap(GENERATED, 76)]
    lines += ["// </auto-generated>", "//"]
    return lines + [f"// {line}" for line in records._wrap(about, 76)]


def render_type(name: str, payload, payloads) -> str:
    """One payload's C# type: its fields, ``Read`` (a parsed JSON tree, held to
    the payload's rules as pythontk validates) and ``ToJson`` (the tree back)."""
    schema = payload.json_schema()
    lines = _header(
        f"pythontk's {name} as C#: Read takes the tree Json.Parse makes and refuses "
        "(FormatException) a required key left out, a null the payload does not "
        "admit, a value of another type or outside its choices; ToJson gives the "
        "tree Json.Write writes, the fields set and no others."
    )
    lines += [
        "using System;",
        "using System.Collections.Generic;",
        "",
        f"namespace {NAMESPACE}",
        "{",
    ]
    lines += records._cs_summary(schema.get("description", "") or name, "    ")
    lines += [f"    public sealed class {name}", "    {"]
    members = []
    for key, prop in schema.get("properties", {}).items():
        cs_type, read, tree = _member(key, prop, payloads)
        field = f"@{key}" if key in records.CS_KEYWORDS else key
        lines += records._cs_summary(prop.get("description", "") or key, "        ")
        lines.append(f"        public {cs_type} {field};")
        members.append((key, field, read, tree))
    lines += [
        "",
        "        /// <summary>One read off a parsed JSON value; null when it is not an object.</summary>",
        "        /// <exception cref=\"FormatException\">The value breaks the payload's rules.</exception>",
        f"        public static {name} Read(object value)",
        "        {",
        "            if (!(value is IDictionary<string, object> o)) return null;",
    ]
    required = schema.get("required", [])
    if required:
        lines.append(
            f'            Wire.Require(o, "{name}", {", ".join(json.dumps(k) for k in required)});'
        )
    # A typed key whose type admits no null is refused as null; an untyped
    # one (any JSON value: an operation's result) admits it.
    valued = [
        key
        for key, prop in schema.get("properties", {}).items()
        if ("type" in prop or "$ref" in prop)
        and not any(n.get("type") == "null" for n in prop.get("anyOf", []))
    ]
    if valued:
        lines.append(f'            Wire.NotNull(o, "{name}", {", ".join(json.dumps(k) for k in valued)});')
    for key, prop in schema.get("properties", {}).items():
        choices = prop.get("enum")
        if choices:
            allowed = ", ".join(json.dumps(str(c)) for c in choices)
            lines.append(f'            Wire.Choice(o, "{key}", {allowed});')
    lines += [f"            return new {name}", "            {"]
    lines += [f"                {field} = {read}," for _, field, read, _ in members]
    lines += [
        "            };",
        "        }",
        "",
        "        /// <summary>This payload as a JSON tree (Json.Write writes it): the fields set, no others.</summary>",
        "        public Dictionary<string, object> ToJson()",
        "        {",
        "            var o = new Dictionary<string, object>();",
    ]
    lines += [f'            Wire.Put(o, "{key}", {tree});' for key, _, _, tree in members]
    lines += ["            return o;", "        }", "    }", "}"]
    return "\n".join(lines) + "\n"


def render_wire() -> str:
    """The conversions every generated type shares: the records' readers plus the writers."""
    lines = _header(
        "The JSON tree's values as the payloads' field types, read as the "
        "records' readers read them (sync_scene_records.py), and the writers back."
    )
    lines += [
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "",
        f"namespace {NAMESPACE}",
        "{",
    ]
    body = records.CS_WIRE.rstrip()
    assert body.endswith("}"), "sync_scene_records.CS_WIRE no longer ends its class"
    body = body[:-1].rstrip() + "\n" + CS_WIRE_WRITE + "}"
    lines += [f"    {line}" if line else "" for line in body.splitlines()]
    lines.append("}")
    return "\n".join(lines) + "\n"


def meta(name: str) -> str:
    """The ``.meta`` a generated type ships with: its GUID derived from its name."""
    guid = uuid.uuid5(uuid.NAMESPACE_URL, GUID_NAMESPACE + name).hex
    return (
        "fileFormatVersion: 2\n"
        f"guid: {guid}\n"
        "MonoImporter:\n"
        "  externalObjects: {}\n"
        "  serializedVersion: 2\n"
        "  defaultReferences: []\n"
        "  executionOrder: 0\n"
        "  icon: {instanceID: 0}\n"
        "  userData: \n"
        "  assetBundleName: \n"
        "  assetBundleVariant: \n"
    )


def core_dir() -> Path:
    """The folder of the core assembly's asmdef, wherever the package keeps it."""
    return records.unity_file(f"{NAMESPACE}.asmdef").parent


def targets() -> list:
    """``[(path, text)]``: every generated file and its ``.meta``."""
    payloads = _payloads()
    out = []
    core = core_dir()
    for name, payload in payloads.items():
        out.append((core / f"{name}.g.cs", render_type(name, payload, payloads)))
        out.append((core / f"{name}.g.cs.meta", meta(name)))
    out.append((core / "Wire.g.cs", render_wire()))
    out.append((core / "Wire.g.cs.meta", meta("Wire")))
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 on drift")
    args = parser.parse_args(argv)
    failed = False
    for path, text in targets():
        failed |= records.sync_text(
            path, text, args.check, "operation contract", "sync_operation_contract.py"
        )
    if not failed:
        print(f"in sync: {len(targets()) // 2} generated contract files")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
