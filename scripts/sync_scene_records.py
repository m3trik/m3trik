_UNITY_CHANNEL = re.compile(
    r'const[ \t]+string[ \t]+\w+[ \t]*=[ \t]*"(?P<key>\w+)";[ \t]*'
    r"//[ \t]*channel\b(?:[^\w\n]+(?P<reader>\w+))?"
)


def _records():
    """``SceneRecords`` from the sibling pythontk checkout (not an installed copy)."""
    checkout = str(REPO_ROOT / "pythontk")
    if checkout not in sys.path:
        sys.path.insert(0, checkout)
    from pythontk import SceneRecords

    return SceneRecords


def _handoff():
    """``HandoffRecord`` from the same checkout as :func:`_records`."""
    _records()  # puts the checkout on sys.path
    from pythontk import HandoffRecord

    return HandoffRecord


#: How a record's ``Merge`` rule reads in the table's *Crosses* column.
MERGE_LABELS = {
    "derive": "re-derived",
    "own": "keeps its own",
    "union": "unites",
    "codec": "domain merge",
}


def render_table(records=None) -> str:
    """The generated region's body: one table per carrier, a row per declared
    record.  A deliverable row says who reads it and what it is computed
    from; a private row says what another scene's copy becomes beside this
    one's (*Crosses*: the record's ``Merge`` rule, and ``portable`` -- it
    rides a DCC hand-off).  Every deliverable is re-derived on a crossing, so
    its table leaves that column out."""
    records = records or _records()
    deliverable = [
        "**`data_export`** -- the deliverable records:",
        "",
        "| Record | Version | Kind | Owner | Reads | Read by | GLB block | Holds |",
        "|---|---|---|---|---|---|---|---|",
    ]
    private = [
        "**`data_internal`** -- the private records:",
        "",
        "| Record | Version | Owner | Crosses | Holds |",
        "|---|---|---|---|---|",
    ]
    for row in records.describe():
        version = row["version"] if row["envelope"] else f"{row['version']} (bare)"
        holds = row["description"].replace("|", "/")
        if row["scope"] == "deliverable":
            # `.get`: a pythontk that predates a column (the CI gate runs
            # against the siblings' pushed branches) must read as drift in
            # the rendered table, not as a traceback.
            glb = row.get("glb")
            transient = row.get("transient")
            deliverable.append(
                "| `{key}` | {version} | {kind} | {owner} | {reads} | {consumers} | {glb} | {holds} |".format(
                    key=row["key"],
                    version=version,
                    # Written for one write and cleared after it.
                    kind=row["kind"] + (", transient" if transient else ""),
                    owner=row["owner"],
                    reads=", ".join(f"`{k}`" for k in row["after"]) or "--",
                    consumers=", ".join(row["consumers"]) or "--",
                    glb=f"v{glb}" if glb else "--",
                    holds=holds,
                )
            )
            continue
        merge = row.get("merge", "")
        crosses = MERGE_LABELS.get(merge, merge)
        if row.get("portable"):
            crosses += ", hand-off"
        private.append(
            "| `{key}` | {version} | {owner} | {crosses} | {holds} |".format(
                key=row["key"],
                version=version,
                owner=row["owner"],
                crosses=crosses,
                holds=holds,
            )
        )
    return "\n".join(deliverable + [""] + private)


def splice(text: str, body: str) -> str:
    """*text* with the marker region replaced by *body*; refuses a missing pair."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0 or end < start:
        raise ValueError(f"{DOC.name} has no '{BEGIN}' ... '{END}' region")
    return text[: start + len(BEGIN)] + "\n" + body + "\n" + text[end:]


def unity_package(unitytk: Path = UNITYTK) -> Path:
    """unitytk's Unity package folder: the ``root`` its pyproject declares in
    ``[tool.m3trik.layers.csharp]`` (the declaration check_layers.py and
    check_csharp.py read), so moving the tree is one edit there. *unitytk*:
    the repo (another workspace's, say)."""
    try:
        import tomllib
    except ImportError:  # pragma: no cover - Python < 3.11
        import tomli as tomllib

    data = tomllib.loads((unitytk / "pyproject.toml").read_text(encoding="utf-8"))
    root = data.get("tool", {}).get("m3trik", {}).get("layers", {}).get("csharp", {})
    if not root.get("root"):
        raise ValueError(
            "unitytk/pyproject.toml declares no [tool.m3trik.layers.csharp] root: "
            "declare the Unity package's folder"
        )
    return unitytk / root["root"]


def unity_file(name: str, unitytk: Path = UNITYTK) -> Path:
    """The one file named *name* under the Unity package (of the *unitytk*
    repo): a hand-written partner a generated file sits beside, wherever a
    move put it."""
    package = unity_package(unitytk)
    found = sorted(package.rglob(name))
    if len(found) != 1:
        raise FileNotFoundError(
            f"{len(found)} files named {name} under {package}: a generated file "
            "sits beside exactly one -- declare the package's root, or rename"
        )
    return found[0]


def unity_settings() -> Path:
    """``UnitytkRecords.cs`` (the core's): the channel list Unity's importers read."""
    return unity_file("UnitytkRecords.cs")


def unity_reader(reader):
    """The file of the importer *reader* names -- ``<reader>.cs`` wherever it
    sits in the Unity package (a feature folder) -- or ``None``."""
    if not reader:
        return None
    found = sorted(unity_package().rglob(f"{reader}.cs"))
    return found[0] if len(found) == 1 else None


def unity_mismatch(records=None) -> dict:
    """``{"undeclared": [...], "unread": [...], "shapeless": [...]}`` --
    channels Unity reads that no record declares for it, records declared for
    Unity it does not read, and records it reads that declare no shape: their
    importer would have no generated reader, nor the generated version it
    reads alone (``<Shape>.CurrentVersion``)."""
    records = records or _records()
    readers = {
        m["key"]: m["reader"]
        for m in _UNITY_CHANNEL.finditer(unity_settings().read_text(encoding="utf-8"))
    }
    specs = {s.key: s for s in records.deliverable() if UNITY_READER in s.consumers}
    return {
        "undeclared": sorted(readers.keys() - specs.keys()),
        "unread": sorted(specs.keys() - readers.keys()),
        "shapeless": sorted(
            k for k in readers.keys() & specs.keys() if not specs[k].shape
        ),
    }


def producer_specs(path: Path) -> set:
    """The ``SceneRecords`` attribute names a ``FbxUtils.PRODUCERS`` table keys on."""
    import ast

    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        target = getattr(node, "target", None) or (
            node.targets[0] if isinstance(node, ast.Assign) and node.targets else None
        )
        if getattr(target, "id", None) != "PRODUCERS":
            continue
        value = getattr(node, "value", None)
        if isinstance(value, ast.Dict):
            return {k.attr for k in value.keys if isinstance(k, ast.Attribute)}
    raise ValueError(f"no PRODUCERS table in {path}")


def registered_producer_specs(host: str, projects=HOOK_PROJECTS) -> set:
    """The ``SceneRecords`` attribute names the producer entry points in
    *projects* register for *host*, read as TOML so nothing is imported; a key
    no record declares comes back as itself."""
    try:
        import tomllib
    except ImportError:  # pragma: no cover - Python < 3.11
        import tomli as tomllib
    from pythontk import RecordSpec

    records = _records()
    names = {
        value.key: name
        for name, value in vars(records).items()
        if isinstance(value, RecordSpec)
    }
    found = set()
    for path in projects:
        if not path.is_file():
            continue
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        points = data.get("project", {}).get("entry-points", {}).get(records.HOOK_GROUP, {})
        for entry in points:
            parts = entry.split(".", 2)
            if len(parts) == 3 and parts[0] == host and parts[1] == "producer":
                found.add(names.get(parts[2], parts[2]))
    return found


def producer_parity() -> list:
    """Unledgered differences between the two DCC producer tables, each with
    the producers registered for its host, as lines."""
    tables = {
        dcc: producer_specs(path) | registered_producer_specs(HOSTS[dcc])
        for dcc, path in FBX_UTILS.items()
    }
    problems = []
    for spec in sorted(set().union(*tables.values())):
        missing = [dcc for dcc, specs in tables.items() if spec not in specs]
        ledgered = PRODUCER_DIVERGENCES.get(spec, (None,))[0]
        for dcc in missing:
            if dcc != ledgered:
                problems.append(f"{dcc} does not produce SceneRecords.{spec}")
    for spec, (dcc, _why) in PRODUCER_DIVERGENCES.items():
        if spec in tables[dcc]:
            problems.append(f"stale ledger row: {dcc} now produces SceneRecords.{spec}")
    return problems


# ------------------------------------------------- the web runtime's blocks
def _spec_names(records) -> dict:
    """``{id(spec): attribute}`` -- SceneRecords' own name for each declaration
    (``ARTICULATION``), the name a generated reader uses for it."""
    spec_type = type(records.SHOTS)
    return {id(v): k for k, v in vars(records).items() if isinstance(v, spec_type)}


def _plain(text: str) -> str:
    """A docstring sentence for another language's doc comment: RST's double
    backticks to single, whitespace to one space."""
    return " ".join(text.replace("``", "`").split())


def _wrap(text: str, width: int = 74) -> list:
    """*text* in lines of at most *width* characters, words whole."""
    lines, line = [], ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    return lines + [line] if line else lines


def jsdoc_type(node: dict) -> str:
    """The JSDoc type of a JSON Schema fragment (``SchemaSpec.json_schema``)."""
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in node:
        return "|".join(dict.fromkeys(jsdoc_type(n) for n in node["anyOf"]))
    if "enum" in node:
        return "|".join(
            f"'{v}'" if isinstance(v, str) else json.dumps(v) for v in node["enum"]
        )
    kind = node.get("type")
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(jsdoc_type(n) for n in node["prefixItems"]) + "]"
        item = jsdoc_type(node["items"]) if "items" in node else "*"
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        values = node.get("additionalProperties")
        return f"Object<string, {jsdoc_type(values)}>" if values else "object"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "*")


def render_typedef(name: str, schema: dict) -> list:
    """One JSDoc ``@typedef`` block for an object schema."""
    lines = ["/**"]
    lines += [f" * {line}" for line in _wrap(_plain(schema.get("description", "")))]
    lines.append(f" * @typedef {{object}} {name}")
    required = set(schema.get("required", ()))
    for key, node in schema.get("properties", {}).items():
        label = key if key in required else f"[{key}]"
        about = _plain(node.get("description", ""))
        lines.append(
            f" * @property {{{jsdoc_type(node)}}} {label}{' ' + about if about else ''}"
        )
    lines.append(" */")
    return lines


def _camel(name: str) -> str:
    """A Python field name as a JavaScript property's (``mime_type`` -> ``mimeType``)."""
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def render_media_js(records) -> list:
    """The lines of ``kernel/records.js`` stating how a file a record names
    rides a GLB (``SceneRecords.GLB_MEDIA``, each field camel-cased), and the
    UV set a lightmap is read through (``LightmapRecord.UV_SET``)."""
    from dataclasses import asdict

    fields = []
    for name, value in asdict(records.GLB_MEDIA).items():
        if isinstance(value, (list, tuple)):
            value = f"Object.freeze([{', '.join(repr(v) for v in value)}])"
        else:
            value = repr(value)
        fields.append(f"{_camel(name)}: {value}")
    lines = ["/**"]
    lines += [f" * {line}" for line in _wrap(_plain(records.GLB_MEDIA.text) + ".")]
    lines += [
        " * The fields are SceneRecords.GLB_MEDIA's, camel-cased.",
        " * @type {Readonly<{name: string, mimeType: string, scale: string, "
        "hdrWeb: ReadonlyArray<string>, radiance: string}>}",
        " */",
        f"export const GLB_MEDIA = Object.freeze({{ {', '.join(fields)} }});",
    ]
    uv_set = getattr(records.shape(records.LIGHTMAPS), "UV_SET", None)
    if uv_set is not None:
        lines += [
            "/** The UV set every lightmap the `lightmaps` record names is read",
            " * through (LightmapRecord.UV_SET): no entry names one. @type {number} */",
            f"export const LIGHTMAP_UV_SET = {int(uv_set)};",
        ]
    return lines


def render_records_js(records=None) -> str:
    """``kernel/records.js``: every block a GLB carries -- each record it
    carries as it stands (``RecordSpec.glb_verbatim``) and the handoff -- and
    the JSDoc typedefs of each declared shape (:data:`WEB_RECORDS`)."""
    records = records or _records()
    names = _spec_names(records)
    lines = ["/*", f"  {_wrap(GENERATED, 72)[0]}"]
    lines += [f"  {line}" for line in _wrap(GENERATED, 72)[1:]]
    lines += [
        "",
        "  The records a deliverable GLB carries in its root extras -- each one",
        "  as it stands, a block in this page's word (readBlock) -- with its key,",
        "  the schema version this page reads, and, where it is declared, its",
        "  shape. A feature reads a block by these, never by a spelling of its own.",
        "*/",
        "",
        "/**",
        " * A record a GLB carries in its root extras, as it stands.",
        " * @typedef {object} GlbRecord",
        " * @property {string} key Its key in the root extras: its record's own.",
        " * @property {number} version Its schema version: the one this page reads.",
        " */",
        "",
    ]
    blocks = [
        (names[id(spec)], spec.key, spec.version)
        for spec in records.glb_records()
    ]
    blocks.append(("HANDOFF", _handoff().KEY, _handoff().VERSION))
    for name, key, version in blocks:
        lines += [
            f"/** The `{key}` record. @type {{Readonly<GlbRecord>}} */",
            f"export const {name} = Object.freeze({{ key: '{key}', version: {version} }});",
        ]
    lines += [
        "/** Every record above, for a pass over all of them. @type {ReadonlyArray<Readonly<GlbRecord>>} */",
        f"export const BLOCKS = Object.freeze([{', '.join(name for name, _key, _version in blocks)}]);",
        "/** Root-extras keys of blocks a GLB written before these carries, which",
        " * nothing reads (SceneRecords.RETIRED_BLOCKS): a file holding one is",
        " * re-exported. @type {ReadonlyArray<string>} */",
        f"export const RETIRED_BLOCK_KEYS = Object.freeze([{', '.join(repr(key) for key in records.RETIRED_BLOCKS)}]);",
    ]
    lines += render_media_js(records)
    shapes = [records.shape(spec) for spec in records.glb_records()]
    shapes.append(records.shape(records.HANDOFF))
    shapes = [shape for shape in shapes if shape is not None]
    for shape in shapes:
        schema = shape.json_schema(reader=GLB_READER)
        lines += [
            "",
            f"/* {'-' * 12} the `{shape.__name__}` block, declared in pythontk {'-' * 12} */",
        ]
        lines += [""] + render_typedef(shape.__name__, schema)
        for name, node in schema.get("$defs", {}).items():
            lines += [""] + render_typedef(name, node)
    return "\n".join(lines) + "\n"


# ------------------------------------------------------ the C# record types
#: C# keywords a payload key could collide with (escaped as ``@key``).
CS_KEYWORDS = frozenset(
    "abstract as base bool break byte case catch char checked class const "
    "continue decimal default delegate do double else enum event explicit "
    "extern false finally fixed float for foreach goto if implicit in int "
    "interface internal is lock long namespace new null object operator out "
    "override params private protected public readonly ref return sbyte "
    "sealed short sizeof stackalloc static string struct switch this throw "
    "true try typeof uint ulong unchecked unsafe ushort using virtual void "
    "volatile while".split()
)
#: The namespace a record type's ``.meta`` GUID is derived in: one stable
#: GUID per record, whatever folder its reader sits in.
CS_GUID_NAMESPACE = "https://github.com/m3trik/unitytk/records/"


def _cs_name(def_name: str, root: str) -> str:
    """A declared shape's nested C# class name: the root itself is
    ``Payload``; another drops the family prefix the root's name gives
    (``ArticulationRecord`` -> ``Articulation``: ``ArticulationJoint`` is
    ``ArticulationRecord.Joint``)."""
    if def_name == root:
        return "Payload"
    family = root[: -len("Record")] if root.endswith("Record") else root
    rest = def_name[len(family) :] if def_name.startswith(family) else ""
    return rest if rest[:1].isupper() else def_name


def _cs_member(key: str, node: dict, root: str) -> tuple:
    """``(C# type, read expression over ``o``)`` of one payload key."""
    if "anyOf" in node:
        options = [n for n in node["anyOf"] if n.get("type") != "null"]
        node = options[0] if len(options) == 1 else {}
    if "$ref" in node:
        cls = _cs_name(node["$ref"].rsplit("/", 1)[-1], root)
        return cls, f'Wire.Obj(o, "{key}", {cls}.Read)'
    kind = node.get("type")
    if kind == "array":
        prefix = node.get("prefixItems")
        items = prefix or [node.get("items", {})]
        # A tuple's length is part of its type: pythontk's validate refuses
        # another ("expected 3 items, got 4"), so the reader does too.
        fixed = f", {len(prefix)}" if prefix else ""
        if all(item.get("type") == "number" for item in items):
            return "double[]", f'Wire.Nums(o, "{key}"{fixed})'
        item = items[0]
        if "$ref" in item:
            cls = _cs_name(item["$ref"].rsplit("/", 1)[-1], root)
            return f"List<{cls}>", f'Wire.Objs(o, "{key}", {cls}.Read{fixed})'
        if all(item.get("type") == "string" for item in items):
            return "List<string>", f'Wire.Strs(o, "{key}"{fixed})'
        return "IList<object>", f'Wire.Elements(o, "{key}"{fixed})'
    simple = {
        "string": ("string", "Str"),
        "integer": ("int?", "Int"),
        "number": ("double?", "Num"),
        "boolean": ("bool?", "Bool"),
    }
    if kind in simple:
        cs, reader = simple[kind]
        return cs, f'Wire.{reader}(o, "{key}")'
    if kind == "object":
        # A free object (no spec of its own); where its values are declared
        # objects ({section: {setting: value}}), each is held to that too.
        values = node.get("additionalProperties")
        objects = ", objectValues: true" if isinstance(values, dict) and values.get("type") == "object" else ""
        return "IDictionary<string, object>", f'Wire.Dict(o, "{key}"{objects})'
    return "object", f'Wire.Get(o, "{key}")'


def _cs_summary(text: str, indent: str) -> list:
    """A ``/// <summary>`` block for *text* (escaped for XML)."""
    text = _plain(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    lines = _wrap(text, 92 - len(indent))
    if len(lines) <= 1:
        return [f"{indent}/// <summary>{text}</summary>"]
    return (
        [f"{indent}/// <summary>"]
        + [f"{indent}/// {line}" for line in lines]
        + [f"{indent}/// </summary>"]
    )


#: The generated readers' conversions -- the JSON tree's values as the fields'
#: types. A number converts the way the hand-written readers always did
#: (``Convert``, invariant culture), so a value that is not one fails loudly
#: rather than reading as null.
CS_WIRE = """\
// The JSON tree's values as the fields' types, each taken as the JSON type its
// shape declares -- never converted from another -- so a value that is not one
// fails loudly (FormatException) rather than reading as something it is not.
static class Wire
{
    public static object Get(IDictionary<string, object> o, string key)
        => o.TryGetValue(key, out var v) ? v : null;

    public static string Str(IDictionary<string, object> o, string key)
    {
        object v = Get(o, key);
        if (v == null) return null;
        return v as string ?? throw new FormatException($"'{key}' is not a string");
    }

    // A JSON number: what the parser gives it as (double, or an integer type),
    // never a string or a boolean.
    static double Number(object v, string where)
    {
        if (v is string || v is bool || !(v is IConvertible))
            throw new FormatException($"{where} is not a number");
        return Convert.ToDouble(v, CultureInfo.InvariantCulture);
    }

    public static double? Num(IDictionary<string, object> o, string key)
    {
        object v = Get(o, key);
        return v == null ? (double?)null : Number(v, $"'{key}'");
    }

    // An integer an int holds. A fraction is refused, as pythontk's validate
    // refuses a number that is not an integer; so is a value past an int's
    // range (1e12, an infinity) -- never truncated or wrapped into another.
    // The JSON reader gives every number as a double, so 2.0 reads as 2.
    public static int? Int(IDictionary<string, object> o, string key)
    {
        double? v = Num(o, key);
        if (!v.HasValue) return null;
        double d = v.Value;
        if (d != Math.Floor(d))
            throw new FormatException($"'{key}': {d.ToString(CultureInfo.InvariantCulture)} is not an integer");
        if (d < int.MinValue || d > int.MaxValue)
            throw new FormatException($"'{key}': {d.ToString(CultureInfo.InvariantCulture)} is past an integer's range");
        return (int)d;
    }

    public static bool? Bool(IDictionary<string, object> o, string key)
    {
        object v = Get(o, key);
        if (v == null) return null;
        return v is bool b ? b : throw new FormatException($"'{key}' is not a boolean");
    }

    // An array: null when absent or null, and a FormatException when it is
    // something else -- or, where the shape fixes its length (a tuple, its
    // length passed), when it holds another number of items.
    public static IList<object> Elements(IDictionary<string, object> o, string key, int length = -1)
    {
        object v = Get(o, key);
        if (v == null) return null;
        if (!(v is IList<object> list))
            throw new FormatException($"'{key}' is not an array");
        if (length >= 0 && list.Count != length)
            throw new FormatException($"'{key}' holds {list.Count} items, not {length}");
        return list;
    }

    public static double[] Nums(IDictionary<string, object> o, string key, int length = -1)
    {
        var list = Elements(o, key, length);
        if (list == null) return null;
        var items = new double[list.Count];
        for (int i = 0; i < list.Count; i++)
            items[i] = Number(list[i], $"'{key}'[{i}]");
        return items;
    }

    public static List<string> Strs(IDictionary<string, object> o, string key, int length = -1)
    {
        var list = Elements(o, key, length);
        if (list == null) return null;
        var items = new List<string>(list.Count);
        for (int i = 0; i < list.Count; i++)
            items.Add(list[i] as string ?? throw new FormatException($"'{key}'[{i}] is not a string"));
        return items;
    }

    // An object a declared spec reads; null when absent or null, and a
    // FormatException when it is something else.
    public static T Obj<T>(IDictionary<string, object> o, string key, Func<object, T> read)
        where T : class
    {
        object v = Get(o, key);
        if (v == null) return null;
        if (!(v is IDictionary<string, object>))
            throw new FormatException($"'{key}' is not an object");
        return read(v);
    }

    // An object the shape leaves free (no spec of its own): null when absent
    // or null, and a FormatException when it is something else -- or, where
    // the shape declares each of its values an object, when one is not.
    public static IDictionary<string, object> Dict(IDictionary<string, object> o, string key,
                                                   bool objectValues = false)
    {
        object v = Get(o, key);
        if (v == null) return null;
        if (!(v is IDictionary<string, object> d))
            throw new FormatException($"'{key}' is not an object");
        if (objectValues)
            foreach (var pair in d)
                if (!(pair.Value is IDictionary<string, object>))
                    throw new FormatException($"'{key}'.{pair.Key} is not an object");
        return d;
    }

    // A list of objects a declared spec reads, every item one.
    public static List<T> Objs<T>(IDictionary<string, object> o, string key, Func<object, T> read,
                                  int length = -1)
    {
        var list = Elements(o, key, length);
        if (list == null) return null;
        var items = new List<T>(list.Count);
        for (int i = 0; i < list.Count; i++)
        {
            if (!(list[i] is IDictionary<string, object>))
                throw new FormatException($"'{key}'[{i}] is not an object");
            items.Add(read(list[i]));
        }
        return items;
    }

    // Each key the shape requires is present.
    public static void Require(IDictionary<string, object> o, string owner, params string[] keys)
    {
        foreach (string key in keys)
            if (!o.ContainsKey(key))
                throw new FormatException($"{owner}: missing required '{key}'");
    }

    // Each key the shape never writes null for, when present, is not null.
    public static void NotNull(IDictionary<string, object> o, string owner, params string[] keys)
    {
        foreach (string key in keys)
            if (o.TryGetValue(key, out object v) && v == null)
                throw new FormatException($"{owner}: '{key}' is null");
    }

    // A value the shape enumerates is one of its choices.
    public static void Choice(IDictionary<string, object> o, string key, params string[] allowed)
    {
        object v = Get(o, key);
        if (v == null) return;
        string s = v as string ?? Convert.ToString(v, CultureInfo.InvariantCulture);
        if (Array.IndexOf(allowed, s) < 0)
            throw new FormatException($"'{key}': {s} is not one of {string.Join(", ", allowed)}");
    }
}
"""


def render_record_cs(spec, shape) -> str:
    """The C# types of record *spec*'s declared *shape*: one class per
    declared object, nested in ``<shape>.Shape`` of ``public static partial
    class <shape>``, and the version a reader reads (``<shape>.CurrentVersion``,
    *spec*'s declared one -- no importer spells it). The other half -- the
    reader's policy: its channel, what a null means -- is hand-written beside
    it."""
    schema = shape.json_schema(reader=UNITY_READER)
    root = shape.__name__
    objects = [(root, schema)] + list(schema.get("$defs", {}).items())
    about = (
        f"The `{spec.key}` record's payload as pythontk declares it ({root}): "
        "one class per declared object, a field per key. Read takes the parsed "
        "JSON tree -- an object as IDictionary<string, object>, an array as "
        "IList<object>, a number as double -- and reads as pythontk validates: "
        "a required key left out, a null the shape does not admit, a value that "
        "is not of its type (an array or object that is something else, an "
        "integer with a fraction or past an int's range, an item of a list of "
        "objects that is not one), a tuple of another length, or a value "
        "outside its declared choices throws a FormatException, so a reader "
        "refuses the record; an optional key left out reads as null, and a key "
        "the shape does not declare is ignored. Not JsonUtility, which cannot "
        "say null (a channel with no limit). CurrentVersion is the one version "
        "a reader reads. The policy -- what a null means -- is the reader's "
        "own, in the hand-written half of this partial class."
    )
    lines = ["// <auto-generated>"]
    lines += [f"// {line}" for line in _wrap(GENERATED, 76)]
    lines += ["// </auto-generated>", "//"]
    lines += [f"// {line}" for line in _wrap(about, 76)]
    lines += [
        "using System;",
        "using System.Collections.Generic;",
        "using System.Globalization;",
        "",
        f"public static partial class {root}",
        "{",
        f"    /// <summary>The `{spec.key}` record's schema version: the one read.</summary>",
        f"    public const int CurrentVersion = {spec.version};",
        "",
        f"    /// <summary>The `{spec.key}` record's declared shape ({root}).</summary>",
        "    public static class Shape",
        "    {",
    ]
    for def_name, node in objects:
        cls = _cs_name(def_name, root)
        lines += _cs_summary(node.get("description", ""), "        ")
        lines += [f"        public sealed class {cls}", "        {"]
        members = []
        for key, prop in node.get("properties", {}).items():
            cs_type, read = _cs_member(key, prop, root)
            field = f"@{key}" if key in CS_KEYWORDS else key
            lines += _cs_summary(prop.get("description", ""), "            ")
            lines.append(f"            public {cs_type} {field};")
            members.append((field, read))
        lines += [
            "",
            "            /// <summary>One read off a parsed JSON value; null when it is not an object.</summary>",
            f"            public static {cls} Read(object value)",
            "            {",
            "                if (!(value is IDictionary<string, object> o)) return null;",
        ]
        required = node.get("required", [])
        if required:
            keys = ", ".join(json.dumps(key) for key in required)
            lines.append(f'                Wire.Require(o, "{cls}", {keys});')
        # A key whose shape admits no null (no "null" in its anyOf) is refused
        # as null wherever it appears, as pythontk's validate refuses it.
        valued = [
            key
            for key, prop in node.get("properties", {}).items()
            if not any(n.get("type") == "null" for n in prop.get("anyOf", []))
        ]
        if valued:
            keys = ", ".join(json.dumps(key) for key in valued)
            lines.append(f'                Wire.NotNull(o, "{cls}", {keys});')
        for key, prop in node.get("properties", {}).items():
            choices = prop.get("enum") or next(
                (n["enum"] for n in prop.get("anyOf", []) if n.get("enum")), None
            )
            if choices:
                allowed = ", ".join(json.dumps(str(c)) for c in choices)
                lines.append(f'                Wire.Choice(o, "{key}", {allowed});')
        lines += [
            f"                return new {cls}",
            "                {",
        ]
        lines += [f"                    {field} = {read}," for field, read in members]
        lines += ["                };", "            }", "        }", ""]
    lines += [f"        {line}" if line else "" for line in CS_WIRE.splitlines()]
    lines += ["    }", "}"]
    return "\n".join(lines) + "\n"


def record_cs_meta(spec) -> str:
    """The ``.meta`` a generated record type ships with: a GUID derived from
    the record's key alone, so regenerating -- or moving its reader to another
    folder -- never mints a new one (every file in the unitytk package ships with
    its own)."""
    import uuid

    guid = uuid.uuid5(uuid.NAMESPACE_URL, CS_GUID_NAMESPACE + spec.key).hex
    return (
        "fileFormatVersion: 2\n"
        f"guid: {guid}\n"
        "MonoImporter:\n"
        "  externalObjects: {}\n"
        "  serializedVersion: 2\n"
        "  defaultReferences: []\n"
        "  executionOrder: 0\n"
        "  icon: {instanceID: 0}\n"
        "  userData: \n"
        "  assetBundleName: \n"
        "  assetBundleVariant: \n"
    )


def record_cs_targets(records=None) -> list:
    """``[(spec, shape, .cs path)]``: every record Unity reads that declares
    its shape, written beside the importer its channel line names."""
    records = records or _records()
    readers = {
        m["key"]: m["reader"]
        for m in _UNITY_CHANNEL.finditer(unity_settings().read_text(encoding="utf-8"))
    }
    targets = []
    for spec in records.deliverable():
        shape = records.shape(spec)
        if shape is None or UNITY_READER not in spec.consumers:
            continue
        reader = unity_reader(readers.get(spec.key))
        if reader is not None:
            targets.append((spec, shape, reader.parent / f"{shape.__name__}.g.cs"))
    return targets


