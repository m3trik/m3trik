#!/usr/bin/python
# coding=utf-8
"""Generate the Unity package's readers of unitytk's own contracts -- and fail when they drift.

A contract only unitytk writes and reads (its Python half writes it, its Unity
package reads it) is declared once, in unitytk's Python, as a typed
``SchemaSpec``; this renders its C# reader into the package with the renderer
the scene records' readers come from (``sync_scene_records.render_record_cs``):
one class per declared object, a field per key, read off Core's parsed JSON and
refusing what the declaration refuses, and ``CurrentVersion``, the one version
the reader reads. A contract pythontk declares for several readers is a scene
record's business (``sync_scene_records.py``); one unitytk keeps to itself is
this script's.

:data:`CONTRACTS` lists them: the declaration, the package folder its reader
goes in, and the namespace its types sit in: the hand-written half's
(``<Shape>.cs``, the other half of the partial class) where there is one, as
for the record readers, else the contract's own. check_csharp.py holds every
``*.g.cs`` to its generator (``GENERATORS``), so a declaration changed without
a run fails there.

:data:`DEFAULTS` lists the defaults a pythontk dataclass declares that the
package's runtime starts from too (the render effects' recipe: the highlight's
colour, the pulse's cadence): each rendered as a static class of constants, one
per field the package reads, so a default changed in pythontk reaches Unity by
a run of this, never by a second hand edit.

The declarations are read from the workspace's checkouts (pythontk's and
unitytk's, which imports it), never an installed copy: CI's gate job installs
neither.

:data:`STATES` lists the named states a pythontk class declares that the
package starts from too (an indicator's emission states: off, green, amber...):
each table rendered as the states it holds, in declaration order.

Usage:
    python sync_unity_contracts.py            # rewrite the readers (idempotent)
    python sync_unity_contracts.py --check    # exit 1 on drift
"""

import argparse
import importlib
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import List, NamedTuple, Optional, Tuple

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import sync_scene_records as records  # noqa: E402  (beside this script)

REPO_ROOT = records.REPO_ROOT
#: The checkouts the declarations are read from: unitytk's, and pythontk's,
#: which holds the defaults and which unitytk imports.
CHECKOUTS = (REPO_ROOT / "pythontk", records.UNITYTK)
for _checkout in CHECKOUTS:
    if str(_checkout) not in sys.path:
        sys.path.insert(0, str(_checkout))

GENERATED = (
    "GENERATED by m3trik/scripts/sync_unity_contracts.py from unitytk's own "
    "declarations -- do not edit; run the script after changing a declaration."
)


class Contract(NamedTuple):
    """One contract unitytk declares for itself.

    key: its name (the reader's ``.meta`` GUID derives from it).
    shape: ``module:Class``, the typed SchemaSpec; its ``VERSION`` is the one read.
    folder: where its reader goes, under the package root.
    subject: what the reader's summaries call it.
    namespace: the namespace the reader's types sit in where no hand-written
        half (``<Shape>.cs`` beside it) declares one: that half's is the
        reader's (:func:`namespace`), so a contract with one names none.
    """

    key: str
    shape: str
    folder: str
    subject: str
    namespace: Optional[str] = None


CONTRACTS: Tuple[Contract, ...] = (
    Contract(
        key="sheet_plan",
        shape="unitytk.sheets.sheet_plan:SheetPlan",
        folder="Features/Manifests/Editor",
        subject="A sheet plan",
    ),
    Contract(
        key="sheet_settings",
        shape="unitytk.sheets.sheet_settings:SheetSettings",
        folder="Features/Manifests/Editor",
        subject="A sheet settings file",
        namespace="M3trik.Unitytk.Manifests",
    ),
)


class Defaults(NamedTuple):
    """The defaults a pythontk dataclass declares, restated in the package as constants.

    key: its name (the file's ``.meta`` GUID derives from it).
    source: ``module:Class``, the dataclass whose field defaults are read.
    folder: where the file goes, under the package root.
    namespace: the namespace its class sits in.
    name: the C# class (and the file's name).
    subject: what its summary calls them.
    fields: the fields the package reads, restated in this order: the
        coupling is to what Unity reads, so a field it does not is no constant.
    extra: class attributes (numbers) restated after the fields.
    """

    key: str
    source: str
    folder: str
    namespace: str
    name: str
    subject: str
    fields: Tuple[str, ...]
    extra: Tuple[str, ...] = ()


DEFAULTS: Tuple[Defaults, ...] = (
    Defaults(
        key="effect_recipe",
        source="pythontk.core_utils.engines.shots.effect_recipe:EffectRecipe",
        folder="Features/RenderEffects/Runtime",
        namespace="M3trik.Unitytk.RenderEffects",
        name="EffectRecipeDefaults",
        subject=(
            "How render effects are keyed by default, as pythontk's EffectRecipe "
            "declares it (the recipe the DCC panels and the Shot Manifest key "
            "with): a highlight's colours, linear light, and its pulse's cadence, "
            "in seconds and shares of a cycle; a fade's length in frames at "
            "ReferenceFps"
        ),
        fields=("fade_frames", "pulse_period", "pulse_duty", "pulse_ramp", "pulse_bright", "pulse_dim"),
        extra=("REFERENCE_FPS",),
    ),
)


def _shape(contract: Contract):
    module, name = contract.shape.split(":")
    return getattr(importlib.import_module(module), name)


def reader(contract: Contract) -> Path:
    """Where *contract*'s reader goes: ``<Shape>.g.cs`` in its folder."""
    return records.unity_package() / contract.folder / f"{_shape(contract).__name__}.g.cs"


def namespace(contract: Contract) -> Optional[str]:
    """The namespace *contract*'s reader sits in: its hand-written half's
    (``records.cs_namespace``), else the contract's own (``None``: the global one).

    Raises:
        ValueError: the contract names one beside a hand-written half that
            declares one: the halves of a partial class share it, so it is
            stated once, there.
    """
    declared = records.cs_namespace(reader(contract))
    if declared is not None and contract.namespace is not None:
        raise ValueError(
            f"{contract.key}: names namespace {contract.namespace}, but {_shape(contract).__name__}.cs "
            f"declares {declared}: a reader with a hand-written half takes its namespace; name none"
        )
    return declared or contract.namespace


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.lower().split("_"))


class States(NamedTuple):
    """Tables of named emission states a pythontk class declares, restated in the package.

    key: its name (the file's ``.meta`` GUID derives from it).
    source: ``module:Class``, the class whose tables are read.
    tables: ``(attribute, C# member)`` of each ``{name: {"tint": [r, g, b], "weight": w}}`` table.
    folder: where the file goes, under the package root.
    namespace: the namespace its class sits in.
    name: the C# class (and the file's name).
    subject: what its summary calls them.
    """

    key: str
    source: str
    tables: Tuple[Tuple[str, str], ...]
    folder: str
    namespace: str
    name: str
    subject: str


STATES: Tuple[States, ...] = (
    States(
        key="emission_states",
        source="pythontk.core_utils.engines.textures.emissive_groups:EmissiveGroupsModel",
        tables=(("DEFAULT_STATES", "Tinted"), ("WEIGHT_STATES", "Weighted")),
        folder="Features/RenderEffects/Runtime",
        namespace="M3trik.Unitytk.RenderEffects",
        name="EmissionStateDefaults",
        subject=(
            "The states an indicator's emission has when none are given it, as pythontk's "
            "Emissive Groups declare them (what the authoring tool gives a group, and what "
            "a build gives an emission track it makes itself): a tint and a weight each. "
            "Tinted: an emission a state can colour; Weighted: one it can only dim (a map, "
            "a black colour)"
        ),
    ),
)


def render_states(states: States) -> str:
    """The C# tables of *states*: a property per table, each a fresh array of its states in
    declaration order (a caller owns what it is handed).

    Raises:
        TypeError: a state that is no ``{"tint": [r, g, b], "weight": w}``.
    """
    module, name = states.source.split(":")
    cls = getattr(importlib.import_module(module), name)
    lines = [
        "// <auto-generated>",
        "// GENERATED by m3trik/scripts/sync_unity_contracts.py from pythontk's",
        f"// {name} -- do not edit; run the script after changing its states.",
        "// </auto-generated>",
        "using UnityEngine;",
        "",
        f"namespace {states.namespace}",
        "{",
        f"    /// <summary>{states.subject} ({states.source}).</summary>",
        f"    internal static class {states.name}",
        "    {",
    ]
    for attr, member in states.tables:
        lines.append(f"        /// <summary>{name}.{attr}.</summary>")
        lines.append(f"        public static EmissionState[] {member} => new[]")
        lines.append("        {")
        for state, entry in getattr(cls, attr).items():
            tint, weight = (entry or {}).get("tint"), (entry or {}).get("weight")
            if not (
                isinstance(tint, (list, tuple))
                and len(tint) == 3
                and all(map(records.is_number, tint))
                and records.is_number(weight)
            ):
                raise TypeError(f"{name}.{attr}[{state!r}]: no tint [r, g, b] and weight to restate")
            rgb = ", ".join(records.cs_float(c) for c in tint)
            lines.append(
                f"            new EmissionState {{ name = {records.cs_string(state)}, "
                f"tint = new Color({rgb}, 1f), weight = {records.cs_float(weight)} }},"
            )
        lines.append("        };")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def render_defaults(defaults: Defaults) -> str:
    """The C# constants of *defaults*: one per field it names, in that order,
    then its extras; a string, bool or number a constant of its type
    (``records.cs_scalar``), an RGB a ``Color`` (alpha 1).

    Raises:
        TypeError: a field the dataclass lacks or with no plain default (a
            ``default_factory`` or a required field), or a default with no C#
            constant.
        ValueError: a number C# cannot write.
    """
    import dataclasses

    module, name = defaults.source.split(":")
    cls = getattr(importlib.import_module(module), name)
    declared = {field.name: field for field in dataclasses.fields(cls)}
    members = []
    for attr in defaults.fields:
        if attr not in declared:
            raise TypeError(f"{name}.{attr}: no such field")
        if declared[attr].default is dataclasses.MISSING:
            raise TypeError(f"{name}.{attr}: no default to restate (a default_factory or a required field)")
        members.append((attr, declared[attr].default))
    members += [(attr, getattr(cls, attr)) for attr in defaults.extra]
    lines = [
        "// <auto-generated>",
        "// GENERATED by m3trik/scripts/sync_unity_contracts.py from pythontk's",
        f"// {name} -- do not edit; run the script after changing its defaults.",
        "// </auto-generated>",
        "using UnityEngine;",
        "",
        f"namespace {defaults.namespace}",
        "{",
        f"    /// <summary>{defaults.subject} ({defaults.source}).</summary>",
        f"    internal static class {defaults.name}",
        "    {",
    ]
    for attr, value in members:
        member = _pascal(attr)
        lines.append(f"        /// <summary>{name}.{attr}'s default.</summary>")
        try:
            scalar = records.cs_scalar(value)
            if scalar:
                lines.append(f"        public const {scalar[0]} {member} = {scalar[1]};")
            elif isinstance(value, tuple) and len(value) == 3 and all(map(records.is_number, value)):
                rgb = ", ".join(records.cs_float(c) for c in value)
                lines.append(f"        public static readonly Color {member} = new Color({rgb}, 1f);")
            else:
                raise TypeError(f"{name}.{attr}: no C# constant for {value!r}")
        except ValueError as e:  # a number C# cannot write
            raise ValueError(f"{name}.{attr}: {e}") from None
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def render(contract: Contract) -> str:
    """The C# reader of *contract*."""
    shape = _shape(contract)
    about = (
        f"{contract.subject} as unitytk declares it ({contract.shape}): one class "
        "per declared object, a field per key. Read takes the parsed JSON tree -- "
        "an object as IDictionary<string, object>, an array as IList<object>, a "
        "number as double -- and reads as the declaration validates: a required "
        "key left out, a null it does not admit, a value not of its type throws a "
        "FormatException, so the reader refuses the file; an optional key left out "
        "reads as null, and a key it does not declare is ignored. CurrentVersion "
        "is the one version read."
    )
    spec = SimpleNamespace(key=contract.key, version=shape.VERSION)
    return records.render_record_cs(
        spec,
        shape,
        generated=GENERATED,
        subject=contract.subject,
        about=about,
        namespace=namespace(contract),
    )


def targets() -> List[Tuple[Path, str]]:
    """``[(path, text)]``: every file this script writes, its ``.meta`` files too
    (check_csharp.py holds each ``*.g.cs`` to it)."""
    root = records.unity_package()
    out = []
    for contract in CONTRACTS:
        path = reader(contract)
        out.append((path, render(contract)))
        out.append((path.with_name(path.name + ".meta"), records.script_cs_meta("contract/" + contract.key)))
    for defaults in DEFAULTS:
        path = root / defaults.folder / f"{defaults.name}.g.cs"
        out.append((path, render_defaults(defaults)))
        out.append((path.with_name(path.name + ".meta"), records.script_cs_meta("defaults/" + defaults.key)))
    for states in STATES:
        path = root / states.folder / f"{states.name}.g.cs"
        out.append((path, render_states(states)))
        out.append((path.with_name(path.name + ".meta"), records.script_cs_meta("states/" + states.key)))
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 on drift; write nothing")
    args = parser.parse_args(argv)
    drifted = False
    for path, text in targets():
        drifted |= records.sync_text(path, text, args.check, "reader", script="sync_unity_contracts.py")
    if args.check and not drifted:
        print(f"in sync: {len(CONTRACTS)} contract(s), {len(DEFAULTS)} set(s) of defaults, {len(STATES)} of states")
    return 1 if drifted else 0


if __name__ == "__main__":
    sys.exit(main())
