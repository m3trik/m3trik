class TestGenerated(unittest.TestCase):
    def setUp(self):
        scratch = _scratch("generated")
        self.addCleanup(scratch.cleanup)
        self.root = Path(scratch.dir_path())
        self.written = {}
        self.generators = {GENERATOR: lambda: list(self.written.items())}
        _tree(self.root, {"Pkg/Core/P.Core.asmdef": {}}, {})

    def write(self, rel: str, text: str, generated: bool = True) -> Path:
        path = self.root / "Pkg" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        if generated:
            self.written[path] = text
        return path

    def problems(self):
        layout = cl.CSharpLayout(self.root, {"root": "Pkg", "order": ["Core"]})
        return cc.generated(layout, self.generators)

    def test_current_generated_files_pass_crlf_included(self):
        path = self.write("Core/Wire.g.cs", HEADER + "class Wire { }\n")
        path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
        self.write("Core/Wire.g.cs.meta", "guid: 1\n")
        self.assertEqual(self.problems(), [])

    def test_a_hand_edit_fails_naming_the_generator(self):
        path = self.write("Core/Wire.g.cs", HEADER + "class Wire { }\n")
        path.write_text(HEADER + "class Wire { int hand; }\n", encoding="utf-8")
        (problem,) = self.problems()
        self.assertIn("Core/Wire.g.cs", problem)
        self.assertIn(f"run python {GENERATOR}", problem)

    def test_a_file_with_no_header_or_an_unknown_generator_fails(self):
        self.write("Core/Bare.g.cs", "class Bare { }\n", generated=False)
        self.write(
            "Core/Odd.g.cs",
            HEADER.replace("sync_fake", "sync_other") + "class Odd { }\n",
            generated=False,
        )
        problems = "\n".join(self.problems())
        self.assertIn("Core/Bare.g.cs: no '// <auto-generated>' header", problems)
        self.assertIn(GENERATOR, problems)  # the generators it may name
        self.assertIn("names m3trik/scripts/sync_other.py", problems)

    def test_an_orphan_or_missing_file_fails(self):
        self.write("Core/Orphan.g.cs", HEADER + "class Orphan { }\n", generated=False)
        missing = self.write("Core/Gone.g.cs", HEADER + "class Gone { }\n")
        missing.unlink()
        moved = self.root / "Old" / "Moved.g.cs"
        self.written[moved] = HEADER
        problems = "\n".join(self.problems())
        self.assertIn(f"Core/Orphan.g.cs: {GENERATOR} does not write it", problems)
        self.assertIn(f"Core/Gone.g.cs is missing: run python {GENERATOR}", problems)
        self.assertIn("Old/Moved.g.cs, outside the declared C# root", problems)

    def test_a_generator_that_cannot_run_is_one_failure(self):
        self.write("Core/Wire.g.cs", HEADER + "class Wire { }\n")

        def broken():
            raise ImportError("No module named 'pythontk'")

        self.generators[GENERATOR] = broken
        (problem,) = self.problems()
        self.assertIn(f"{GENERATOR} could not run", problem)


class TestMain(unittest.TestCase):
    def test_check_update_and_the_strict_rule(self):
        """``--check`` fails on a new violation with its fix, ``--update``
        freezes it in the workspace's own baseline, and a generated-file
        failure is never frozen."""
        with _scratch("main") as tmp:
            root = Path(tmp.dir_path())
            repo = root / "unitytk"
            (repo / "unitytk").mkdir(parents=True)
            (repo / "pyproject.toml").write_text(
                '[project]\nname = "unitytk"\n\n[tool.m3trik.layers.csharp]\n'
                'root = "Pkg"\norder = ["Features/*", "Kernel"]\nkernel = "Kernel"\n',
                encoding="utf-8",
            )
            _tree(
                repo,
                {
                    "Pkg/Kernel/P.Kernel.asmdef": {"includePlatforms": ["Editor"]},
                    "Pkg/Features/A/P.A.asmdef": {"includePlatforms": ["Editor"]},
                },
                {
                    "Pkg/Kernel/K.cs": "/// <remarks>Prior art: none fit.</remarks>\nclass K { }\n",
                    "Pkg/Features/A/A.cs": "class A { void F() { Debug.Log(1); } }\n",
                },
            )
            out = io.StringIO()
            # The real generators write the real workspace: none of this one.
            nothing = {GENERATOR: lambda: []}
            with contextlib.redirect_stdout(out), mock.patch.dict(
                cc.GENERATORS, nothing, clear=True
            ):
                failed = cc.main(["--workspace", str(root), "unitytk"])
                updated = cc.main(["--update", "--workspace", str(root)])
                passed = cc.main(["--workspace", str(root), "unitytk"])
                (repo / "Pkg" / "Features" / "A" / "Hand.g.cs").write_text("class H { }\n")
                strict = cc.main(["--workspace", str(root), "unitytk"])
                refrozen = cc.main(["--update", "--workspace", str(root)])
            frozen = cl.load_baseline(cc.baseline_file(root))
        self.assertEqual((failed, updated, passed, strict, refrozen), (1, 0, 0, 1, 1))
        text = out.getvalue()
        self.assertIn(
            "[FAIL] unitytk: bypass: A.cs: Debug.Log -- at Features/A/A.cs:1: ", text
        )
        self.assertIn("(strict: never frozen)", text)
        self.assertEqual(
            frozen, {"unitytk": ["bypass: A.cs: Debug.Log", "prior-art: P.A.asmdef"]}
        )

    def test_a_named_package_without_the_declaration_fails(self):
        with _scratch("undeclared") as tmp:
            root = Path(tmp.dir_path())
            (root / "unitytk").mkdir()
            (root / "unitytk" / "pyproject.toml").write_text('[project]\nname = "unitytk"\n')
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                code = cc.main(["--workspace", str(root), "unitytk"])
        self.assertEqual(code, 1)
        self.assertIn("declares no [tool.m3trik.layers.csharp]", out.getvalue())


