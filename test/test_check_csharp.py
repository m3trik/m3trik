class TestLexing(unittest.TestCase):
    def test_comments_and_strings_are_blanked_lines_kept(self):
        text = (
            'var a = "Undo.RecordObject(x)"; // Debug.Log("no")\n'
            "/* Undo.ClearAll();\n   Debug.Log(1); */ Debug.Log(2);\n"
            "var b = @\"Debug.Log(\"\"q\"\")\n#if UNITY_EDITOR\"; char c = '\"';\n"
            'var d = $"{Debug.Log2(\'}\')} and {{Undo.X}} {M("Undo.Y")}";\n'
        )
        code = cc.code_only(text)
        self.assertEqual(len(code), len(text))
        self.assertEqual(code.count("\n"), text.count("\n"))
        self.assertNotIn("Undo", code)  # in a string, a comment, an escaped {{ }}
        self.assertEqual(code.count("Debug.Log"), 2)  # line 2's and the hole's
        self.assertIn("Debug.Log(2)", code.splitlines()[2])
        self.assertNotIn("#if", code)  # inside a verbatim string

    def test_editor_regions(self):
        code = textwrap.dedent(
            """\
            a
            #if UNITY_EDITOR
            b
            #if X
            c
            #endif
            #else
            d
            #endif
            #if !UNITY_EDITOR
            e
            #else
            f
            #endif
            #if UNITY_EDITOR && X
            g
            #elif Y
            h
            #endif
            #if UNITY_EDITOR || X
            i
            #endif
            #if !(X && UNITY_EDITOR)
            j
            #endif
            """
        )
        lines = code.splitlines()
        editor = cc.editor_lines(code)
        marked = {lines[i] for i, on in enumerate(editor) if on and lines[i].isalpha()}
        self.assertEqual(marked, {"b", "c", "f", "g"})


