def _scratch(name: str):
    """A scratch folder in the house temp home (``ptk.TempArtifacts``), gone on a
    clean exit and kept for debugging on a failure."""
    pythontk = str(SCRIPTS.parents[1] / "pythontk")
    if pythontk not in sys.path:
        sys.path.insert(0, pythontk)
    from pythontk import TempArtifacts

    return TempArtifacts.scoped(f"check_csharp_{name}")


def _tree(root: Path, asmdefs: dict, files: dict) -> None:
    """``{folder/Name.asmdef: fields}`` and ``{path: C# text}`` under *root*."""
    for rel, fields in asmdefs.items():
        data = {"name": Path(rel).stem, "references": [], "autoReferenced": True}
        data.update(fields)
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(json.dumps(data), encoding="utf-8")
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(textwrap.dedent(text), encoding="utf-8")


