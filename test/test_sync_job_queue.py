#!/usr/bin/python
# coding=utf-8
"""``sync_job_queue.py``: pythontk's job-queue layout, restated as the C#
constants of extapps' Unity Scripts package -- generated, held, never retyped."""

import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

SCRIPTS = Path(__file__).resolve().parent.parent / "scripts"
sys.path.insert(0, str(SCRIPTS))

import sync_job_queue as s  # noqa: E402


@unittest.skipUnless((s.REPO_ROOT / "pythontk").is_dir(), "pythontk is not checked out beside m3trik")
class TestSyncJobQueue(unittest.TestCase):
    def test_every_name_of_the_layout_is_a_constant(self):
        text = s.render()
        queue = s._job_queue()
        for name in (queue.WORKER, queue.STOP, queue.LEASE, *queue.SUFFIXES.values(), *queue.WORKER_STATES):
            self.assertIn(f'"{name}"', text)
        self.assertTrue(text.startswith("// <auto-generated>"))
        self.assertIn("m3trik/scripts/sync_job_queue.py", text.splitlines()[1])

    def test_a_stale_file_is_drift_and_a_write_fixes_it(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "QueueLayout.g.cs"
            target.write_text("// stale\n", encoding="utf-8")
            kernel = Path(tmp) / "Kernel" / "QueueLayout.g.cs"
            kernel.parent.mkdir()
            with mock.patch.object(s, "TARGET", target), mock.patch.object(s, "UNITYTK_TARGET", kernel), \
                    mock.patch.object(s.records, "REPO_ROOT", Path(tmp)):
                self.assertEqual(s.main(["--check"]), 1)
                self.assertEqual(s.main([]), 0)
                self.assertEqual(s.main(["--check"]), 0)

    def test_unitytks_kernel_reads_the_layout_in_its_own_namespace_with_its_meta(self):
        written = dict(s.targets())
        self.assertIn(s.UNITYTK_TARGET, written)
        self.assertEqual(
            s.UNITYTK_TARGET.relative_to(s.REPO_ROOT).as_posix(),
            "unitytk/com.m3trik.unitytk/Kernel/Editor/QueueLayout.g.cs",
        )
        self.assertIn("namespace M3trik.Unitytk.Kernel\n", written[s.UNITYTK_TARGET])
        meta = written[s.UNITYTK_TARGET.with_name("QueueLayout.g.cs.meta")]
        self.assertIn("guid: ", meta)
        self.assertEqual(meta, dict(s.targets())[s.UNITYTK_TARGET.with_name("QueueLayout.g.cs.meta")], "a stable GUID")
        self.assertIn("namespace M3trik.UnityScripts\n", written[s.TARGET])

    def test_the_session_server_retypes_none_of_the_layout(self):
        server = s.REPO_ROOT / "unitytk" / "com.m3trik.unitytk" / "Kernel" / "Editor" / "SessionServer.cs"
        if not server.is_file():
            self.skipTest("unitytk is not checked out")
        text = server.read_text(encoding="utf-8")
        queue = s._job_queue()
        for name in (queue.WORKER, queue.STOP, queue.LEASE, *queue.SUFFIXES.values(), *queue.WORKER_STATES):
            self.assertNotIn(f'"{name}"', text, f"SessionServer retypes {name!r}: read QueueLayout")
        self.assertIn("QueueLayout.", text)

    def test_the_committed_file_is_in_sync(self):
        if not s.TARGET.is_file():
            self.skipTest("extapps is not checked out")
        self.assertEqual(s.main(["--check"]), 0)


if __name__ == "__main__":
    unittest.main()
