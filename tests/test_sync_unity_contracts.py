"""Tests for scripts/sync_unity_contracts.py: each of unitytk's own contracts has
its C# reader generated into the Unity package, in its namespace, under its
generator's header, with a .meta whose GUID never changes; the package holds
the readers as the script writes them. A pythontk dataclass's defaults are
restated as C# constants, and a default with no C# constant is refused."""

import dataclasses
import os
import re
import subprocess
import sys
import tempfile
import textwrap
import types
import unittest
import uuid
from pathlib import Path
from unittest import mock

SCRIPTS = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPTS))

import sync_scene_records as records  # noqa: E402
import sync_unity_contracts as contracts  # noqa: E402


class TestSyncUnityContracts(unittest.TestCase):
    def test_its_targets_need_no_installed_package(self):
        """CI's gate job clones the siblings and installs none of them: each
        script puts the checkouts it reads on the path itself. Only unitytk's
        was, so reading its contracts (unitytk imports pythontk) failed there
        with ModuleNotFoundError: pythontk, hidden here by editable installs.
        Fixed: 2026-11-26"""
        probe = textwrap.dedent(
            f"""
            import sys
            from pathlib import Path
            root = Path({str(records.REPO_ROOT)!r}).resolve()
            def checkout(entry):
                path = Path(entry or ".").resolve()
                return path == root or (path.parent == root and not path.name.startswith("."))
            sys.path[:] = [p for p in sys.path if not checkout(p)]
            sys.path.insert(0, {str(SCRIPTS)!r})
            import sync_unity_contracts
            print(len(sync_unity_contracts.targets()))
            """
        )
        env = {k: v for k, v in os.environ.items() if k.upper() != "PYTHONPATH"}
        with tempfile.TemporaryDirectory() as tmp:
            done = subprocess.run(
                [sys.executable, "-c", probe], cwd=tmp, env=env, capture_output=True, text=True, timeout=120
            )
        self.assertEqual(done.returncode, 0, done.stderr[-2000:])
        self.assertEqual(int(done.stdout.split()[-1]), len(contracts.targets()))

    def test_the_sheet_plan_reader_sits_in_the_manifests_feature_and_its_namespace(self):
        targets = dict(contracts.targets())
        reader = records.unity_package() / "Features/Manifests/Editor/SheetPlan.g.cs"
        text = targets[reader]
        self.assertTrue(text.startswith("// <auto-generated>\n// GENERATED by m3trik/scripts/sync_unity_contracts.py"))
        self.assertIn("namespace M3trik.Unitytk.Manifests\n{\n    public static partial class SheetPlan", text)
        self.assertIn(f"public const int CurrentVersion = {contracts._shape(contracts.CONTRACTS[0]).VERSION};", text)
        for shape in ("Payload", "PlanStep", "PlanAction", "PlanSource"):
            self.assertIn(f"public sealed class {shape}", text)

    def test_the_sheet_settings_reader_sits_beside_the_plans(self):
        targets = dict(contracts.targets())
        text = targets[records.unity_package() / "Features/Manifests/Editor/SheetSettings.g.cs"]
        self.assertIn("namespace M3trik.Unitytk.Manifests\n{\n    public static partial class SheetSettings", text)
        for key in ("sheet", "deliveries", "extras"):
            self.assertIn(f"public List<string> {key};" if key != "sheet" else "public string sheet;", text)

    def test_the_meta_guid_derives_from_the_contract_key_alone(self):
        targets = dict(contracts.targets())
        meta = records.unity_package() / "Features/Manifests/Editor/SheetPlan.g.cs.meta"
        guid = uuid.uuid5(uuid.NAMESPACE_URL, records.CS_GUID_NAMESPACE + "contract/sheet_plan").hex
        self.assertIn(f"guid: {guid}\n", targets[meta])

    def test_the_package_holds_the_readers_as_written(self):
        self.assertEqual(contracts.main(["--check"]), 0)

    def test_a_namespace_wraps_the_types_and_no_namespace_leaves_a_record_as_it_was(self):
        shape = contracts._shape(contracts.CONTRACTS[0])
        spec = type("Spec", (), {"key": "sheet_plan", "version": 1})
        plain = records.render_record_cs(spec, shape)
        wrapped = records.render_record_cs(spec, shape, namespace="X.Y")
        self.assertNotIn("namespace", plain)
        body = plain.split("using System.Globalization;\n\n", 1)[1].rstrip("\n").split("\n")
        expected = "namespace X.Y\n{\n" + "\n".join(f"    {line}" if line else "" for line in body) + "\n}\n"
        self.assertTrue(wrapped.endswith(expected), "the same types, indented one level")

    def test_a_reader_with_a_hand_written_half_sits_in_that_halfs_namespace(self):
        """A partial class's halves share one namespace, so the generated half
        takes the hand-written one's (``records.cs_namespace``, as the record
        readers do) instead of restating it; a contract that declares one beside
        such a half is refused. Added: 2026-11-26"""
        plan = contracts.CONTRACTS[0]
        with tempfile.TemporaryDirectory() as tmp, mock.patch.object(records, "unity_package", return_value=Path(tmp)):
            folder = Path(tmp) / plan.folder
            folder.mkdir(parents=True)
            (folder / "SheetPlan.cs").write_text("using System;\n\nnamespace A.B\n{\n}\n", encoding="utf-8")
            self.assertIn("namespace A.B\n{\n    public static partial class SheetPlan", contracts.render(plan._replace(namespace=None)))
            with self.assertRaisesRegex(ValueError, r"sheet_plan: .*SheetPlan\.cs declares A\.B"):
                contracts.render(plan._replace(namespace="X.Y"))
            self.assertNotIn("namespace", contracts.render(plan._replace(namespace=None, folder="Elsewhere")))


class _Lights:
    """Tables of named emission states, one of them malformed."""

    STATES = {"off": {"tint": [1.0, 1.0, 1.0], "weight": 0.0}, "amber": {"tint": [1.0, 0.5, 0.0], "weight": 1.0}}
    BROKEN = {"dim": {"weight": 0.5}}


@dataclasses.dataclass
class _Recipe:
    """A dataclass whose defaults each have a C# constant."""

    loops: bool = True
    period: float = 2.86
    frames: int = 15
    tint: tuple = (1.0, 0.5, 0)
    TICK = 30  # a class attribute, not a field: restated only when ``extra`` names it


class TestRenderDefaults(unittest.TestCase):
    """``render_defaults``: a dataclass's field defaults as C# constants."""

    MODULE = "_unity_defaults_fixture"

    def setUp(self):
        module = types.ModuleType(self.MODULE)
        sys.modules[self.MODULE] = module
        self.addCleanup(sys.modules.pop, self.MODULE, None)
        self.module = module

    def defaults(self, cls, extra=(), fields=None):
        """*cls*'s defaults, restating *fields* (every field by default)."""
        setattr(self.module, cls.__name__, cls)
        return contracts.Defaults(
            key="fixture",
            source=f"{self.MODULE}:{cls.__name__}",
            folder="Features/Fixture/Runtime",
            namespace="X.Y",
            name="FixtureDefaults",
            subject="A fixture's defaults",
            fields=tuple(f.name for f in dataclasses.fields(cls)) if fields is None else fields,
            extra=extra,
        )

    def members(self, text):
        return [line.strip() for line in text.splitlines() if line.strip().startswith("public ")]

    def test_a_bool_a_number_and_an_rgb_each_render_as_a_constant_in_declaration_order(self):
        text = contracts.render_defaults(self.defaults(_Recipe))
        self.assertIn("namespace X.Y\n{\n    /// <summary>A fixture's defaults (", text)
        self.assertIn("    internal static class FixtureDefaults\n", text)
        self.assertEqual(
            self.members(text),
            [
                "public const bool Loops = true;",
                "public const float Period = 2.86f;",
                "public const float Frames = 15.0f;",  # an int is a float constant
                "public static readonly Color Tint = new Color(1.0f, 0.5f, 0.0f, 1f);",
            ],
        )
        self.assertIn("/// <summary>_Recipe.period's default.</summary>", text)

    def test_a_table_of_named_states_renders_each_in_declaration_order_and_a_malformed_one_is_refused(self):
        states = contracts.States(
            key="fixture", source=f"{__name__}:_Lights", tables=(("STATES", "Tinted"),), folder="Features/X/Runtime",
            namespace="X.Y", name="FixtureStates", subject="A fixture's states",
        )
        text = contracts.render_states(states)
        self.assertIn("    internal static class FixtureStates\n", text)
        self.assertIn("        public static EmissionState[] Tinted => new[]\n", text)
        self.assertEqual(
            [line.strip() for line in text.splitlines() if line.strip().startswith("new EmissionState")],
            [
                'new EmissionState { name = "off", tint = new Color(1.0f, 1.0f, 1.0f, 1f), weight = 0.0f },',
                'new EmissionState { name = "amber", tint = new Color(1.0f, 0.5f, 0.0f, 1f), weight = 1.0f },',
            ],
        )
        with self.assertRaises(TypeError) as refused:
            contracts.render_states(states._replace(tables=(("BROKEN", "Tinted"),)))
        self.assertIn("_Lights.BROKEN['dim']", str(refused.exception))

    def test_a_states_name_is_written_as_a_csharp_string(self):
        """A name was written between quotes as it stood, so a quote or a
        backslash in it made C# that does not compile. Fixed: 2026-11-26"""
        _Lights.ODD = {'say "on" \\': {"tint": [1.0, 1.0, 1.0], "weight": 1.0}}
        self.addCleanup(delattr, _Lights, "ODD")
        states = contracts.States(
            key="fixture", source=f"{__name__}:_Lights", tables=(("ODD", "Tinted"),), folder="Features/X/Runtime",
            namespace="X.Y", name="FixtureStates", subject="A fixture's states",
        )
        self.assertIn('new EmissionState { name = "say \\"on\\" \\\\", tint', contracts.render_states(states))

    def test_the_packages_emission_states_are_the_emissive_groups_own(self):
        from pythontk.core_utils.engines.textures.emissive_groups import EmissiveGroupsModel

        text = dict((p.name, t) for p, t in contracts.targets())["EmissionStateDefaults.g.cs"]
        for table in (EmissiveGroupsModel.DEFAULT_STATES, EmissiveGroupsModel.WEIGHT_STATES):
            for name in table:
                self.assertIn(f'name = "{name}"', text)

    def test_extra_restates_a_class_attribute_after_the_fields(self):
        text = contracts.render_defaults(self.defaults(_Recipe, extra=("TICK",)))
        self.assertEqual(self.members(text)[-1], "public const float Tick = 30.0f;")
        self.assertEqual(len(self.members(text)), 5)

    def test_only_the_fields_named_are_restated_in_the_order_named(self):
        """The package restates what its runtime reads, so a field pythontk adds
        that Unity does not read is no constant nobody uses. Added: 2026-11-26"""
        text = contracts.render_defaults(self.defaults(_Recipe, fields=("tint", "loops")))
        self.assertEqual(
            self.members(text),
            ["public static readonly Color Tint = new Color(1.0f, 0.5f, 0.0f, 1f);", "public const bool Loops = true;"],
        )
        with self.assertRaisesRegex(TypeError, r"_Recipe\.reach: no such field"):
            contracts.render_defaults(self.defaults(_Recipe, fields=("reach",)))

    def test_the_package_reads_every_effect_recipe_default_it_restates(self):
        """Three of the recipe's defaults (the pulse's lead in and out, the
        audio snap) were restated and read by nothing in the package.
        Fixed: 2026-11-26"""
        (recipe,) = contracts.DEFAULTS
        generated = dict((p.name, t) for p, t in contracts.targets())[f"{recipe.name}.g.cs"]
        restated = re.findall(r"public (?:const|static readonly) \w+ (\w+) =", generated)
        sources = "\n".join(
            p.read_text(encoding="utf-8") for p in records.unity_package().rglob("*.cs") if not p.name.endswith(".g.cs")
        )
        self.assertTrue(restated)
        for member in restated:
            with self.subTest(member=member):
                self.assertTrue(f"{recipe.name}.{member}" in sources, f"{member}: restated, and read by nothing")

    def test_a_string_default_is_a_csharp_string_constant(self):
        @dataclasses.dataclass
        class Named:
            label: str = 'a "b"'

        self.assertEqual(self.members(contracts.render_defaults(self.defaults(Named))), ['public const string Label = "a \\"b\\"";'])

    def test_a_default_with_no_csharp_constant_is_refused(self):
        @dataclasses.dataclass
        class Unset:
            label: object = None

        with self.assertRaisesRegex(TypeError, r"Unset\.label: no C# constant for None"):
            contracts.render_defaults(self.defaults(Unset))

        @dataclasses.dataclass
        class Pair:
            span: tuple = (1.0, 2.0)

        with self.assertRaisesRegex(TypeError, r"Pair\.span: no C# constant"):
            contracts.render_defaults(self.defaults(Pair))

        @dataclasses.dataclass
        class Letters:
            channels: tuple = ("r", "g", "b")

        with self.assertRaisesRegex(TypeError, r"Letters\.channels: no C# constant"):
            contracts.render_defaults(self.defaults(Letters))

    def test_a_field_with_no_plain_default_is_refused_by_name(self):
        @dataclasses.dataclass
        class Listed:
            items: list = dataclasses.field(default_factory=list)

        @dataclasses.dataclass
        class Required:
            size: float

        for cls, attr in ((Listed, "items"), (Required, "size")):
            with self.subTest(cls=cls.__name__):
                with self.assertRaisesRegex(TypeError, rf"{cls.__name__}\.{attr}: no default .*default_factory"):
                    contracts.render_defaults(self.defaults(cls))

    def test_a_float_is_written_as_its_shortest_csharp_literal(self):
        @dataclasses.dataclass
        class Spread:
            whole: float = 1
            tiny: float = 1e-05
            huge: float = 1e20
            tint: tuple = (0.0, 0.088656, 0.723055)

        self.assertEqual(
            self.members(contracts.render_defaults(self.defaults(Spread))),
            [
                "public const float Whole = 1.0f;",
                "public const float Tiny = 1e-05f;",
                "public const float Huge = 1e+20f;",
                "public static readonly Color Tint = new Color(0.0f, 0.088656f, 0.723055f, 1f);",
            ],
        )

        for reach in (float("inf"), 1e300):
            @dataclasses.dataclass
            class Endless:
                far: float = reach

            with self.subTest(reach=reach), self.assertRaisesRegex(ValueError, r"Endless\.far: no C# float literal"):
                contracts.render_defaults(self.defaults(Endless))


